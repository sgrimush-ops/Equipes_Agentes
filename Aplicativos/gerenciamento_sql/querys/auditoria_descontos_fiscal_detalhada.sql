SELECT *
FROM (
    WITH CTE_LOG_FISCAL AS (
        SELECT /*+ MATERIALIZE */
            S.NROEMPRESA,
            S.NROCHECKOUT,
            S.SEQLOGSEGPDV,
            S.DTAHOREMISSAO,
            S.SEQUSUARIO AS SEQ_FISCAL,
            S.METODO,
            DOC.DTAMOVIMENTO,
            DOC.SERIE,
            DOC.COO AS NRO_CUPOM,
            IT.SEQITEM AS NRO_ITEM,
            V.VALOR AS VLR_DESC_LOG_FISCAL
        FROM CONSINCOMONITOR.TB_LOGSEGURANCAPDV S
        INNER JOIN CONSINCOMONITOR.TB_LOGSEGDOCTOPDV DOC
            ON DOC.NROEMPRESA = S.NROEMPRESA
           AND DOC.NROCHECKOUT = S.NROCHECKOUT
           AND DOC.SEQLOGSEGPDV = S.SEQLOGSEGPDV
        LEFT JOIN CONSINCOMONITOR.TB_LOGSEGITEMPDV IT
            ON IT.NROEMPRESA = S.NROEMPRESA
           AND IT.NROCHECKOUT = S.NROCHECKOUT
           AND IT.SEQLOGSEGPDV = S.SEQLOGSEGPDV
        LEFT JOIN CONSINCOMONITOR.TB_LOGSEGVALORPDV V
            ON V.NROEMPRESA = S.NROEMPRESA
           AND V.NROCHECKOUT = S.NROCHECKOUT
           AND V.SEQLOGSEGPDV = S.SEQLOGSEGPDV
        WHERE S.DTAHOREMISSAO >= TRUNC(:DT1)
          AND S.DTAHOREMISSAO < TRUNC(:DT2) + 1
          AND S.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
          AND (
              NVL(UPPER(TRIM(:LT1)), '0') IN ('0', 'TODAS', 'TODOS')
              OR INSTR(',' || REPLACE(:LT1, ' ', '') || ',', ',' || TO_CHAR(S.NROEMPRESA) || ',') > 0
          )
          AND S.METODO IN ('mtDescontoItemDiferencaPreco', 'mtDescontoCupom')
    ),
    CTE_MANUAL AS (
        SELECT /*+ MATERIALIZE */
            L.NROEMPRESA AS LOJA,
            L.DTAHOREMISSAO AS DTA_ORDEM,
            TO_CHAR(L.DTAHOREMISSAO, 'DD/MM/YYYY HH24:MI:SS') AS DATA_HORA,
            L.NROCHECKOUT AS PDV,
            L.NRO_CUPOM AS CUPOM_COO,
            CF.SEQITEMDF AS ITEM,
            'MANUAL (USUARIO)' AS ORIGEM_DESCONTO,
            CASE
                WHEN L.METODO = 'mtDescontoItemDiferencaPreco' THEN '02-DESCONTO NO ITEM (DIF. PRECO)'
                WHEN L.METODO = 'mtDescontoCupom' THEN '01-DESCONTO NO CUPOM (SUBTOTAL)'
                ELSE L.METODO
            END AS MODALIDADE_DESCONTO,
            CF.CODPRODUTO AS COD_PRODUTO,
            P.DESCCOMPLETA AS PRODUTO,
            CF.QUANTIDADE AS QTD_VENDIDA,
            ROUND(NVL(CF.VLRITEM, 0) + NVL(CF.VLRDESCONTO, 0), 2) AS VLR_BRUTO_NUM,
            ROUND(
                CASE
                    WHEN L.METODO = 'mtDescontoCupom' THEN NVL(CF.VLRDESCONTO, L.VLR_DESC_LOG_FISCAL)
                    ELSE NVL(L.VLR_DESC_LOG_FISCAL, NVL(CF.VLRDESCONTO, 0))
                END,
            2) AS VLR_DESC_NUM,
            ROUND(NVL(CF.VLRITEM, 0), 2) AS VLR_LIQ_NUM,
            CF.SEQOPERADOR AS ID_OPERADOR,
            UOP.CODUSUARIO AS LOGIN_OPERADOR,
            UOP.NOME AS NOME_OPERADOR_CAIXA,
            L.SEQ_FISCAL AS ID_FISCAL,
            UFISC.CODUSUARIO AS LOGIN_FISCAL,
            UFISC.NOME AS NOME_FISCAL_AUTORIZADOR,
            CASE
                WHEN CF.SEQOPERADOR = L.SEQ_FISCAL THEN 'SIM (OPERADOR = FISCAL)'
                ELSE 'NAO'
            END AS AUTO_LIBERACAO
        FROM CTE_LOG_FISCAL L
        INNER JOIN CONSINCO.MFL_CUPOMFISCAL CF
            ON CF.NROEMPRESA = L.NROEMPRESA
           AND CF.NROCHECKOUT = L.NROCHECKOUT
           AND CF.DTAMOVIMENTO = L.DTAMOVIMENTO
           AND CF.NUMERODF = L.NRO_CUPOM
           AND CF.SEQITEMDF = NVL(L.NRO_ITEM, CF.SEQITEMDF)
           AND CF.STATUSCF != 'C'
           AND CF.STATUSITEM != 'C'
        LEFT JOIN CONSINCO.MAP_PRODUTO P
            ON P.SEQPRODUTO = CF.CODPRODUTO
        LEFT JOIN CONSINCO.GE_USUARIO UOP
            ON UOP.SEQUSUARIO = CF.SEQOPERADOR
        LEFT JOIN CONSINCO.GE_USUARIO UFISC
            ON UFISC.SEQUSUARIO = L.SEQ_FISCAL
    )
    SELECT
        U.LOJA,
        U.DATA_HORA,
        U.PDV,
        U.CUPOM_COO,
        U.ITEM,
        U.COD_PRODUTO,
        U.PRODUTO,
        U.QTD_VENDIDA,
        'R$ ' || TO_CHAR(NVL(U.VLR_BRUTO_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS VLR_BRUTO_ITEM,
        'R$ ' || TO_CHAR(NVL(U.VLR_DESC_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS VLR_DESCONTO,
        'R$ ' || TO_CHAR(NVL(U.VLR_LIQ_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS VLR_LIQUIDO_PAGO,
        CASE
            WHEN NVL(U.VLR_BRUTO_NUM, 0) > 0 THEN TO_CHAR(ROUND((NVL(U.VLR_DESC_NUM, 0) / U.VLR_BRUTO_NUM) * 100, 2), 'FM999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') || ' %'
            ELSE '0,00 %'
        END AS PERC_DESCONTO,
        U.ID_OPERADOR,
        U.LOGIN_OPERADOR,
        U.NOME_OPERADOR_CAIXA,
        U.ID_FISCAL,
        U.LOGIN_FISCAL,
        U.NOME_FISCAL_AUTORIZADOR,
        U.AUTO_LIBERACAO,
        U.ORIGEM_DESCONTO,
        U.MODALIDADE_DESCONTO
    FROM CTE_MANUAL U
    ORDER BY
        U.DTA_ORDEM DESC,
        U.LOJA,
        U.CUPOM_COO,
        U.ITEM
)
