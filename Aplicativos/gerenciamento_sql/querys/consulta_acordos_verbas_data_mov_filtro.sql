SELECT * FROM (
WITH CTE_TITULOS_ACORDO AS (
SELECT /*+ MATERIALIZE */ DISTINCT
NROACORDO, NROEMPRESA, NROEMPRESA_TITULO, SEQTITULO, OBRIGDIREITO,
ABERTOQUITADO, VLRPAGO, DTAVENCIMENTO, DTAQUITACAO, CODESPECIE
FROM (
SELECT
TR.NROACORDO, NVL(TR.NROEMPRACORDOPROMOC, NVL(TR.NROEMPRESA, T.NROEMPRESA)) AS NROEMPRESA,
T.NROEMPRESA AS NROEMPRESA_TITULO, T.SEQTITULO, T.OBRIGDIREITO, T.ABERTOQUITADO,
NVL(T.VLRPAGO, 0) AS VLRPAGO, T.DTAVENCIMENTO, T.DTAQUITACAO, NVL(T.CODESPECIE, 'ACORDO') AS CODESPECIE
FROM FI_TITULO T
INNER JOIN MSU_ACORDOTITULORECEB TR ON TR.LINKERP = T.SEQTITULO
WHERE T.SITUACAO != 'C'
UNION
SELECT
TR.NROACORDO, NVL(TR.NROEMPRACORDOPROMOC, NVL(TR.NROEMPRESA, T.NROEMPRESA)) AS NROEMPRESA,
T.NROEMPRESA AS NROEMPRESA_TITULO, T.SEQTITULO, T.OBRIGDIREITO, T.ABERTOQUITADO,
NVL(T.VLRPAGO, 0) AS VLRPAGO, T.DTAVENCIMENTO, T.DTAQUITACAO, NVL(T.CODESPECIE, 'ACORDO') AS CODESPECIE
FROM FI_TITULO T
INNER JOIN MSU_ACORDOTITULORECEB TR ON (TO_CHAR(TR.NUMERONF) = T.NRODOCUMENTO OR TR.NUMERONF = T.NROTITULO) AND TR.SEQPESSOA = T.SEQPESSOA
WHERE T.SITUACAO != 'C' AND T.OBRIGDIREITO = 'D'
UNION
SELECT
CC.NROACORDO, NVL(CC.NROEMPRESAACORDO, T.NROEMPRESA) AS NROEMPRESA,
T.NROEMPRESA AS NROEMPRESA_TITULO, T.SEQTITULO, T.OBRIGDIREITO, T.ABERTOQUITADO,
NVL(T.VLRPAGO, 0) AS VLRPAGO, T.DTAVENCIMENTO, T.DTAQUITACAO, NVL(T.CODESPECIE, 'ACORDO') AS CODESPECIE
FROM FI_TITULO T
INNER JOIN MSU_CCACORDOPROMOC CC ON CC.SEQTITULO = T.SEQTITULO
WHERE CC.SEQTITULO IS NOT NULL AND T.SITUACAO != 'C'
UNION
SELECT
CD.NROACORDO, NVL(CD.NROEMPRESA, T.NROEMPRESA) AS NROEMPRESA,
T.NROEMPRESA AS NROEMPRESA_TITULO, T.SEQTITULO, T.OBRIGDIREITO, T.ABERTOQUITADO,
NVL(T.VLRPAGO, 0) AS VLRPAGO, T.DTAVENCIMENTO, T.DTAQUITACAO, NVL(T.CODESPECIE, 'ACORDO') AS CODESPECIE
FROM FI_TITULO T
INNER JOIN MSU_CCDIVIDA CD ON CD.SEQTITULO = T.SEQTITULO
WHERE CD.SEQTITULO IS NOT NULL AND T.SITUACAO != 'C'
UNION
SELECT
A.NROACORDO, A.NROEMPRESA, T.NROEMPRESA AS NROEMPRESA_TITULO, T.SEQTITULO,
T.OBRIGDIREITO, T.ABERTOQUITADO, NVL(T.VLRPAGO, 0) AS VLRPAGO,
T.DTAVENCIMENTO, T.DTAQUITACAO, NVL(T.CODESPECIE, 'ACORDO') AS CODESPECIE
FROM MSU_ACORDOPROMOC A
INNER JOIN FI_TITOPERACAO TOA ON TOA.NROPROCESSO = A.SEQPROCESSO AND TRIM(TOA.USUCANCELOU) IS NULL
INNER JOIN FI_TITULO T ON T.SEQTITULO = TOA.SEQTITULO
WHERE T.SITUACAO != 'C' AND A.SEQPROCESSO IS NOT NULL
UNION
SELECT
A.NROACORDO, A.NROEMPRESA, T.NROEMPRESA AS NROEMPRESA_TITULO, T.SEQTITULO,
T.OBRIGDIREITO, T.ABERTOQUITADO, NVL(T.VLRPAGO, 0) AS VLRPAGO,
T.DTAVENCIMENTO, T.DTAQUITACAO, NVL(T.CODESPECIE, 'ACORDO') AS CODESPECIE
FROM FI_TITULO T
INNER JOIN MSU_ACORDOPROMOC A
ON A.SEQFORNECEDOR = T.SEQPESSOA
AND (
T.NROEMPRESA = A.NROEMPRESA
OR (
T.NROEMPRESA IN (1, 3, 15, 50, 900)
AND (
ABS(NVL(T.VLRORIGINAL, 0) - NVL(A.VLRACORDO, 0)) < 0.05
OR EXISTS (
SELECT 1 FROM MSU_ACORDOPROMOCPARCELA P
WHERE P.NROACORDO = A.NROACORDO AND P.NROEMPRESA = A.NROEMPRESA
AND ABS(NVL(T.VLRORIGINAL, 0) - NVL(P.VALORPARCELA, 0)) < 0.05
)
)
)
OR (
A.NROEMPRESA IN (1, 15, 50, 900)
AND NOT EXISTS (
SELECT 1 FROM MSU_ACORDOPROMOC A_LOCAL
WHERE A_LOCAL.NROEMPRESA = T.NROEMPRESA AND A_LOCAL.NROACORDO = T.NROTITULO
)
)
)
AND (
T.NRODOCUMENTO = TO_CHAR(A.NROACORDO)
OR T.NROTITULO = A.NROACORDO
OR (A.SEQPROCESSO IS NOT NULL AND (T.NRODOCUMENTO = TO_CHAR(A.SEQPROCESSO) OR T.NROTITULO = A.SEQPROCESSO))
)
WHERE T.SITUACAO != 'C'
AND T.OBRIGDIREITO = 'D'
AND (
T.SERIEDOC IN ('ACO', 'ACR', 'VRB', 'VER', 'BON', 'DEV')
OR T.CODESPECIE IN ('DESPRE','VERBA','ACORDO','ACRCIM','ACRCOM','ACRINT','ACRLOG','ACRMKT','ACRPRE','ACRTRO','ACRJBP','DEVREC','BONIF','VEXTRA')
)
)
),
CTE_OPERACOES_RAW AS (
SELECT /*+ MATERIALIZE */
O.SEQTITULO,
O.SEQTITOPERACAO,
O.CODOPERACAO,
O.DTAOPERACAO,
CASE
WHEN TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL
THEN GREATEST(NVL(O.DTAHORAALTERACAO, O.DTAALTERACAO), NVL(O.DTACANCELOU, NVL(O.DTAHORAALTERACAO, O.DTAALTERACAO)))
ELSE NVL(O.DTAHORAALTERACAO, O.DTAALTERACAO)
END AS DTAALTERACAO_EFETIVA,
CASE
WHEN TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL
THEN NVL(TRIM(O.USUCANCELOU), TRIM(O.USUALTERACAO)) || ' (CANC)'
ELSE O.USUALTERACAO
END AS USUALTERACAO,
CASE
WHEN (O.OPCANCELADA IS NULL OR TRIM(O.OPCANCELADA) = 'N')
AND TRIM(O.USUCANCELOU) IS NULL
AND O.CODOPERACAO NOT IN (16, 18)
THEN NVL(O.VLROPERACAO, 0)
ELSE 0
END AS VLROPERACAO,
CASE
WHEN (O.OPCANCELADA IS NULL OR TRIM(O.OPCANCELADA) = 'N')
AND TRIM(O.USUCANCELOU) IS NULL
AND O.CODOPERACAO NOT IN (16, 18)
THEN 3
WHEN TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL
THEN 2
ELSE 1
END AS PRIORIDADE_OP
FROM FI_TITOPERACAO O
INNER JOIN CTE_TITULOS_ACORDO TA ON TA.SEQTITULO = O.SEQTITULO
),
CTE_OPERACOES_TITULO AS (
SELECT /*+ MATERIALIZE */
R.SEQTITULO,
MAX(R.DTAOPERACAO) AS MAX_DTAOPERACAO,
MAX(R.DTAALTERACAO_EFETIVA) KEEP (DENSE_RANK LAST ORDER BY R.PRIORIDADE_OP, R.DTAALTERACAO_EFETIVA NULLS FIRST, R.SEQTITOPERACAO) AS MAX_DTAHORAALTERACAO,
MAX(R.USUALTERACAO) KEEP (DENSE_RANK LAST ORDER BY R.PRIORIDADE_OP, R.DTAALTERACAO_EFETIVA NULLS FIRST, R.SEQTITOPERACAO) AS USUALTERACAO,
SUM(R.VLROPERACAO) AS VLROPERACAO
FROM CTE_OPERACOES_RAW R
GROUP BY R.SEQTITULO
),
CTE_AUDIT_CANC AS (
SELECT /*+ MATERIALIZE */
S.NROACORDO, S.NROEMPRESA,
MAX(T.NROEMPRESA) KEEP (DENSE_RANK LAST ORDER BY S.ORD_EMP, CASE WHEN T.SITUACAO = 'C' OR TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL THEN 2 ELSE 1 END, GREATEST(NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)), NVL(O.DTACANCELOU, NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)))) NULLS FIRST, NVL(O.SEQTITOPERACAO, T.SEQTITULO)) AS NROEMPRESA_CANC,
MAX(CASE WHEN T.SITUACAO = 'C' OR TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL THEN NVL(TRIM(O.USUCANCELOU), TRIM(O.USUALTERACAO)) || ' (CANC)' ELSE TRIM(O.USUALTERACAO) END) KEEP (DENSE_RANK LAST ORDER BY S.ORD_EMP, CASE WHEN T.SITUACAO = 'C' OR TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL THEN 2 ELSE 1 END, GREATEST(NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)), NVL(O.DTACANCELOU, NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)))) NULLS FIRST, NVL(O.SEQTITOPERACAO, T.SEQTITULO)) AS USU_CANC,
MAX(GREATEST(NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)), NVL(O.DTACANCELOU, NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO))))) KEEP (DENSE_RANK LAST ORDER BY S.ORD_EMP, CASE WHEN T.SITUACAO = 'C' OR TRIM(O.OPCANCELADA) = 'S' OR TRIM(O.USUCANCELOU) IS NOT NULL THEN 2 ELSE 1 END, GREATEST(NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)), NVL(O.DTACANCELOU, NVL(O.DTAHORAALTERACAO, NVL(O.DTAALTERACAO, T.DTAINCLUSAO)))) NULLS FIRST, NVL(O.SEQTITOPERACAO, T.SEQTITULO)) AS DTA_CANC
FROM (
SELECT A.NROACORDO, A.NROEMPRESA, T.SEQTITULO,
CASE WHEN T.NROEMPRESA = A.NROEMPRESA OR ABS(NVL(T.VLRORIGINAL, 0) - NVL(A.VLRACORDO, 0)) < 0.05 THEN 2 ELSE 1 END AS ORD_EMP
FROM MSU_ACORDOPROMOC A
INNER JOIN FI_TITULO T ON T.SEQPESSOA = A.SEQFORNECEDOR AND T.NROEMPRESA IN (A.NROEMPRESA, 1, 3, 15, 50, 900)
AND (T.NRODOCUMENTO = TO_CHAR(A.NROACORDO) OR T.NROTITULO = A.NROACORDO OR (A.SEQPROCESSO IS NOT NULL AND (T.NRODOCUMENTO = TO_CHAR(A.SEQPROCESSO) OR T.NROTITULO = A.SEQPROCESSO)))
AND T.OBRIGDIREITO = 'D'
AND (T.SERIEDOC IN ('ACO', 'ACR', 'VRB', 'VER', 'BON', 'DEV') OR T.CODESPECIE IN ('DESPRE','VERBA','ACORDO','ACRCIM','ACRCOM','ACRINT','ACRLOG','ACRMKT','ACRPRE','ACRTRO','ACRJBP','DEVREC','BONIF','VEXTRA'))
UNION
SELECT A.NROACORDO, A.NROEMPRESA, O.SEQTITULO, 2 AS ORD_EMP
FROM MSU_ACORDOPROMOC A
INNER JOIN FI_TITOPERACAO O ON O.NROPROCESSO = A.SEQPROCESSO
WHERE A.SEQPROCESSO IS NOT NULL
UNION
SELECT TR.NROACORDO, NVL(TR.NROEMPRACORDOPROMOC, TR.NROEMPRESA) AS NROEMPRESA, TR.LINKERP AS SEQTITULO, 2 AS ORD_EMP
FROM MSU_ACORDOTITULORECEB TR
WHERE TR.LINKERP IS NOT NULL
) S
INNER JOIN FI_TITULO T ON T.SEQTITULO = S.SEQTITULO
LEFT JOIN FI_TITOPERACAO O ON O.SEQTITULO = T.SEQTITULO
GROUP BY S.NROACORDO, S.NROEMPRESA
),
CTE_TITULOS_GLOBAL AS (
SELECT /*+ MATERIALIZE */
TA.NROACORDO, TA.NROEMPRESA, TA.NROEMPRESA_TITULO, TA.SEQTITULO,
DENSE_RANK() OVER (PARTITION BY TA.NROACORDO, TA.NROEMPRESA ORDER BY TA.DTAVENCIMENTO, TA.SEQTITULO) AS NROPARCELA,
COUNT(*) OVER (PARTITION BY TA.NROACORDO, TA.NROEMPRESA) AS QTDPARCELA,
TA.ABERTOQUITADO, NVL(TA.VLRPAGO, 0) AS VLRPAGO, TA.DTAVENCIMENTO, TA.DTAQUITACAO,
TA.CODESPECIE,
TA.CODESPECIE AS ESPECIE_TITULO,
CASE WHEN TA.OBRIGDIREITO = 'D' THEN 'Direito' WHEN TA.OBRIGDIREITO = 'O' THEN 'Obrigação' ELSE TA.OBRIGDIREITO END AS DIREITO_OBRIGACAO,
OP.MAX_DTAOPERACAO, NVL(OP.MAX_DTAHORAALTERACAO, CAST(TA.DTAQUITACAO AS DATE)) AS DTA_ULTIMA_ALTERACAO,
NVL(OP.USUALTERACAO, CASE WHEN TA.DTAQUITACAO IS NOT NULL THEN 'QUITADO' END) AS USU_ULTIMA_ALTERACAO,
NVL(OP.VLROPERACAO, TA.VLRPAGO) AS VLR_ULTIMA_OPERACAO,
CASE WHEN (TA.DTAQUITACAO IS NOT NULL AND TRUNC(TA.DTAQUITACAO) BETWEEN :DT1 AND :DT2)
OR (OP.MAX_DTAOPERACAO IS NOT NULL AND TRUNC(OP.MAX_DTAOPERACAO) BETWEEN :DT1 AND :DT2)
OR (OP.MAX_DTAHORAALTERACAO IS NOT NULL AND TRUNC(OP.MAX_DTAHORAALTERACAO) BETWEEN :DT1 AND :DT2)
THEN 1 ELSE 0 END AS TEVE_MOV_QUITACAO_PERIODO
FROM CTE_TITULOS_ACORDO TA
LEFT JOIN CTE_OPERACOES_TITULO OP ON OP.SEQTITULO = TA.SEQTITULO
),
CTE_ACORDO_RESUMO_GLOBAL AS (
SELECT /*+ MATERIALIZE */
TG.NROACORDO, TG.NROEMPRESA, COUNT(*) AS TOTAL_TITULOS,
SUM(CASE WHEN TG.ABERTOQUITADO = 'A' THEN 1 ELSE 0 END) AS TITULOS_ABERTOS,
SUM(CASE WHEN TG.ABERTOQUITADO = 'Q' THEN 1 ELSE 0 END) AS TITULOS_QUITADOS,
NVL(SUM(TG.VLRPAGO), 0) AS GLOBAL_VLR_QUITADO,
MIN(CASE WHEN TG.ABERTOQUITADO = 'A' THEN TG.DTAVENCIMENTO END) AS MIN_DTAVENCIMENTO_ABERTO,
MAX(TG.DTAVENCIMENTO) AS MAX_DTAVENCIMENTO, MAX(TG.DTAQUITACAO) AS MAX_DTAQUITACAO,
MAX(TG.DIREITO_OBRIGACAO) AS DIREITO_OBRIGACAO
FROM CTE_TITULOS_GLOBAL TG
GROUP BY TG.NROACORDO, TG.NROEMPRESA
),
CTE_ACORDO_ACRJBP AS (
SELECT /*+ MATERIALIZE */
A.NROEMPRESA, A.NROACORDO, NVL(TG.SEQTITULO, 0) AS SEQTITULO,
MAX(A.VLRACORDO) AS VLR_ACORDO_ACRJBP,
MAX(NVL(TG.VLR_ULTIMA_OPERACAO, 0)) AS VLR_BAIXA_ACRJBP
FROM MSUV_ACORDOPROMOC A
LEFT JOIN MSU_ACORDOPROMOC AC ON AC.NROACORDO = A.NROACORDO AND AC.NROEMPRESA = A.NROEMPRESA
LEFT JOIN MAC_TIPOACORDO MTA ON MTA.CODTIPOACORDO = AC.CODTIPOACORDO
LEFT JOIN CTE_TITULOS_GLOBAL TG ON TG.NROACORDO = A.NROACORDO AND TG.NROEMPRESA = A.NROEMPRESA
WHERE (
NVL(TG.ESPECIE_TITULO, TG.CODESPECIE) = 'ACRJBP'
OR UPPER(TRIM(MTA.DESCRICAO)) LIKE '%ACRJBP%'
OR TO_CHAR(AC.CODTIPOACORDO) = 'ACRJBP'
OR UPPER(TRIM(A.DESCACORDO)) LIKE '%ACRJBP%'
)
GROUP BY A.NROEMPRESA, A.NROACORDO, NVL(TG.SEQTITULO, 0)
),
CTE_VALORES_BRUTOS AS (
SELECT /*+ MATERIALIZE */
A.NROEMPRESA, A.NROACORDO, TG.SEQTITULO,
NVL(TG.NROEMPRESA_TITULO, CA.NROEMPRESA_CANC) AS NROEMPRESA_TITULO,
TG.NROPARCELA, TG.QTDPARCELA, AC.SEQPROCESSO,
B.SEQPESSOA AS SEQFORNECEDOR, B.NOMERAZAO, A.DESCACORDO, A.DTAEMISSAO, C.APELIDO,
MAX(A.STATUS) AS STATUS, A.TIPOACORDO, A.DTAFINALVERBA,
NVL(TG.DTAVENCIMENTO, RG.MIN_DTAVENCIMENTO_ABERTO) AS DTAVENCIMENTO,
NVL(TG.DTAQUITACAO, TG.DTA_ULTIMA_ALTERACAO) AS ULTIMO_RECEBIMENTO,
MAX(AC.RESPACORDONOME) AS RESPONSAVEL_FORNECEDOR,
MAX(SUBSTR(A.NUMERONF, 1, 250)) AS NUMERONF,
A.NROPEDIDOSUPRIM,
NVL(TG.DIREITO_OBRIGACAO, RG.DIREITO_OBRIGACAO) AS DIREITO_OBRIGACAO,
NVL(TG.ESPECIE_TITULO, 'ACORDO') AS ESPECIE_TITULO,
CASE
WHEN NVL(RG.TOTAL_TITULOS, 0) > 0 THEN
CASE WHEN NVL(RG.TITULOS_ABERTOS, 0) > 0 THEN 'Aberto' ELSE 'Quitado' END
ELSE 'Sem Título'
END AS ABERTO_QUITADO,
NVL(MAX(A.VLRFINVENCIDO), fValorTitAcordo(A.NROACORDO, A.NROEMPRESA, B.SEQPESSOA, 'V')) AS RAW_VLRFINVENCIDO,
NVL(MAX(A.VLRFINAVENCER), fValorTitAcordo(A.NROACORDO, A.NROEMPRESA, B.SEQPESSOA, 'A')) AS RAW_VLRFINAVENCER,
A.VLRACORDO AS RAW_VLRACORDO,
NVL(RG.GLOBAL_VLR_QUITADO, 0) AS RAW_VLRQUITADO,
GREATEST(
NVL((SELECT COUNT(*) FROM MSU_ACORDOPROMOCPARCELA P WHERE P.NROACORDO = A.NROACORDO AND P.NROEMPRESA = A.NROEMPRESA), 0),
NVL(RG.TOTAL_TITULOS, NVL(TG.QTDPARCELA, 1))
) AS TOTAL_PARCELAS,
NVL(RG.TITULOS_QUITADOS, 0) AS PARCELAS_PAGAS,
GREATEST(
0,
GREATEST(
NVL((SELECT COUNT(*) FROM MSU_ACORDOPROMOCPARCELA P WHERE P.NROACORDO = A.NROACORDO AND P.NROEMPRESA = A.NROEMPRESA), 0),
NVL(RG.TOTAL_TITULOS, NVL(TG.QTDPARCELA, 1))
) - NVL(RG.TITULOS_QUITADOS, 0)
) AS PARCELAS_PENDENTES,
COALESCE(
TG.USU_ULTIMA_ALTERACAO,
CA.USU_CANC,
MAX(CASE WHEN AC.USUCANCELAMENTO IS NOT NULL THEN TRIM(AC.USUCANCELAMENTO) || ' (CANC)' ELSE COALESCE(TRIM(AC.USUALTERACAO), TRIM(AC.USUEXPFINANCEIRO), TRIM(AC.USUAPROVREPROV), TRIM(AC.USUINCLUSAO)) END)
) AS USU_ULTIMA_ALTERACAO,
COALESCE(
TG.DTA_ULTIMA_ALTERACAO,
CA.DTA_CANC,
MAX(COALESCE(AC.DTACANCELAMENTO, AC.DTAALTERACAO, AC.DTAEXPFINANCEIRO, AC.DTAAPROVREPROV, AC.DTAHORINCLUSAO, AC.DTAINCLUSAO))
) AS DTA_ULTIMA_ALTERACAO,
TG.VLR_ULTIMA_OPERACAO,
MAX(JBP.VLR_ACORDO_ACRJBP) AS VLR_ACORDO_ACRJBP,
MAX(JBP.VLR_BAIXA_ACRJBP) AS VLR_BAIXA_ACRJBP
FROM MSUV_ACORDOPROMOC A
INNER JOIN GE_PESSOA B ON B.SEQPESSOA = A.SEQFORNECEDOR
INNER JOIN MAX_COMPRADOR C ON C.SEQCOMPRADOR = A.SEQCOMPRADOR
LEFT JOIN MSU_ACORDOPROMOC AC ON AC.NROACORDO = A.NROACORDO AND AC.NROEMPRESA = A.NROEMPRESA
LEFT JOIN CTE_TITULOS_GLOBAL TG
ON TG.NROACORDO = A.NROACORDO
AND TG.NROEMPRESA = A.NROEMPRESA
AND (
TG.TEVE_MOV_QUITACAO_PERIODO = 1
OR TRUNC(A.DTAEMISSAO) BETWEEN :DT1 AND :DT2
OR (AC.DTAALTERACAO IS NOT NULL AND TRUNC(AC.DTAALTERACAO) BETWEEN :DT1 AND :DT2)
)
LEFT JOIN CTE_ACORDO_RESUMO_GLOBAL RG ON RG.NROACORDO = A.NROACORDO AND RG.NROEMPRESA = A.NROEMPRESA
LEFT JOIN CTE_AUDIT_CANC CA ON CA.NROACORDO = A.NROACORDO AND CA.NROEMPRESA = A.NROEMPRESA
LEFT JOIN CTE_ACORDO_ACRJBP JBP ON JBP.NROEMPRESA = A.NROEMPRESA AND JBP.NROACORDO = A.NROACORDO AND JBP.SEQTITULO = NVL(TG.SEQTITULO, 0)
WHERE (
NVL(TRIM(:LT1), '0') IN ('0', 'TODOS', '')
OR INSTR(',' || UPPER(REPLACE(:LT1, ' ', '')) || ',', ',' || TO_CHAR(A.NROEMPRESA) || ',') > 0
OR (NVL(TG.NROEMPRESA_TITULO, CA.NROEMPRESA_CANC) IS NOT NULL AND INSTR(',' || UPPER(REPLACE(:LT1, ' ', '')) || ',', ',' || TO_CHAR(NVL(TG.NROEMPRESA_TITULO, CA.NROEMPRESA_CANC)) || ',') > 0)
)
AND (NVL(TO_NUMBER(:NR1), 0) != 2 OR A.STATUS != 2)
AND (
NVL(TRIM(:LT2), '0') IN ('0', 'TODOS', '')
OR (
NVL(TG.USU_ULTIMA_ALTERACAO, CA.USU_CANC) IS NOT NULL
AND INSTR(',' || UPPER(REPLACE(:LT2, ' ', '')) || ',', ',' || UPPER(TRIM(REPLACE(NVL(TG.USU_ULTIMA_ALTERACAO, CA.USU_CANC), ' (CANC)', ''))) || ',') > 0
)
)
AND (
NVL(TRIM(:LT3), '0') IN ('0', 'TODOS', '')
OR INSTR(',' || UPPER(REPLACE(:LT3, ' ', '')) || ',', ',' || TO_CHAR(B.SEQPESSOA) || ',') > 0
)
AND (
NVL(TRIM(:LS1), '0 - TODOS') IN ('0 - TODOS', 'TODOS', '', '0')
OR (INSTR(:LS1, ' - ') > 0 AND C.SEQCOMPRADOR = TO_NUMBER(SUBSTR(:LS1, 1, INSTR(:LS1, ' - ') - 1)))
OR TO_CHAR(C.SEQCOMPRADOR) = TRIM(SUBSTR(:LS1, 1, 10))
)
AND (
NVL(TRIM(:LS3), '0') IN ('0', 'TODOS', 'TODAS', '0 - TODOS', '0 - TODAS', '', ' TODAS AS REDES', 'TODAS AS REDES')
OR INSTR(UPPER(:LS3), 'TODA') > 0
OR EXISTS (
SELECT 1 FROM GE_REDEPESSOA RP
INNER JOIN GE_REDE R ON R.SEQREDE = RP.SEQREDE
WHERE RP.SEQPESSOA = B.SEQPESSOA
AND (
UPPER(TRIM(R.DESCRICAO)) = UPPER(TRIM(:LS3))
OR (INSTR(:LS3, ' - ') > 0 AND TO_CHAR(R.SEQREDE) = TRIM(SUBSTR(:LS3, 1, INSTR(:LS3, ' - ') - 1)))
)
)
)
AND (
(A.DTAEMISSAO IS NOT NULL AND TRUNC(A.DTAEMISSAO) BETWEEN :DT1 AND :DT2)
OR (AC.DTAALTERACAO IS NOT NULL AND TRUNC(AC.DTAALTERACAO) BETWEEN :DT1 AND :DT2)
OR NVL(TG.TEVE_MOV_QUITACAO_PERIODO, 0) = 1
