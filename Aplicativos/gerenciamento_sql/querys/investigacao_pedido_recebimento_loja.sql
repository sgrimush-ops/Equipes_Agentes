SELECT
    C.OWNER,
    C.TABLE_NAME,
    C.COLUMN_NAME,
    C.DATA_TYPE,
    C.DATA_LENGTH
FROM ALL_TAB_COLUMNS C
WHERE (
        C.OWNER = USER
        OR C.OWNER LIKE 'CONSINCO%'
      )
  AND (
        C.TABLE_NAME LIKE 'MAC%'
        OR C.TABLE_NAME LIKE 'MAD%'
        OR C.TABLE_NAME LIKE 'MSU%'
        OR C.TABLE_NAME LIKE 'MLO%'
      )
  AND (
        C.COLUMN_NAME LIKE '%RECEB%'
        OR C.COLUMN_NAME LIKE '%PED%'
        OR C.COLUMN_NAME LIKE 'NROPED%'
      )
ORDER BY
    C.OWNER,
    C.TABLE_NAME,
    C.COLUMN_NAME;
SELECT
    'MSU_PSITEMEXPEDIDO' AS FONTE,
    P.NROEMPRESA,
    NULL AS NROEMPDESTINO,
    P.SEQPRODUTO,
    P.NROPEDIDOSUPRIM,
    P.NROEMPRESAPEDVENDA,
    P.NROPEDVENDA,
    NULL AS NROPEDFORNECEDORNUM,
    NULL AS NROPEDFORNECEDOR
FROM MSU_PSITEMEXPEDIDO P
WHERE P.NROPEDVENDA = 56123

UNION ALL

