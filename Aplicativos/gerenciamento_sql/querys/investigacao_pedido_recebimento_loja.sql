SELECT
    'MACV_PSITEMRECEBER' AS FONTE,
    R.NROEMPRESA,
    NULL AS NROEMPDESTINO,
    R.SEQPRODUTO,
    R.NROPEDIDOSUPRIM,
    NULL AS NROEMPRESAPEDVENDA,
    NULL AS NROPEDVENDA,
    R.NROPEDFORNECEDORNUM,
    R.NROPEDFORNECEDOR
FROM MACV_PSITEMRECEBER R
WHERE TO_CHAR(R.NROPEDFORNECEDORNUM) = '56123'
   OR TO_CHAR(R.NROPEDFORNECEDOR) = '56123'
   OR R.NROPEDIDOSUPRIM = 31339

UNION ALL

SELECT
    'MACX_IMPABASTECIMENTO' AS FONTE,
    NULL AS NROEMPRESA,
    NULL AS NROEMPDESTINO,
    NULL AS SEQPRODUTO,
    TO_NUMBER(I.NROPEDORIGEM) AS NROPEDIDOSUPRIM,
    NULL AS NROEMPRESAPEDVENDA,
    I.NROPEDGERADO AS NROPEDVENDA,
    NULL AS NROPEDFORNECEDORNUM,
    NULL AS NROPEDFORNECEDOR
FROM MACX_IMPABASTECIMENTO I
WHERE REGEXP_LIKE(I.NROPEDORIGEM, '^[0-9]+$')
  AND (I.NROPEDGERADO = 56123 OR TO_NUMBER(I.NROPEDORIGEM) = 31339)

ORDER BY
    FONTE,
    NROEMPRESA,
    NROEMPDESTINO,
    SEQPRODUTO;
