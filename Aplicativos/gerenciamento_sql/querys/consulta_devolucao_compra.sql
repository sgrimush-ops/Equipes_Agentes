SELECT * FROM (
WITH REDE_FORNEC AS (
    SELECT /*+ MATERIALIZE */
        RP.SEQPESSOA,
        MAX(R.DESCRICAO) AS REDE
    FROM GE_REDEPESSOA RP
    JOIN GE_REDE R
        ON R.SEQREDE = RP.SEQREDE
    GROUP BY
        RP.SEQPESSOA
), ITENS_BASE AS (
    SELECT /*+ MATERIALIZE */
        N.NROEMPRESA,
        N.NUMERONF,
        N.SEQNF,
        N.TIPNOTAFISCAL,
        N.SEQPESSOA,
        F.NOMERAZAO AS FORNECEDOR,
        NVL(RF.REDE, 'SEM REDE') AS REDE,
        N.DTAEMISSAO,
        COALESCE(NULLIF(TRIM(I.OBSERVACAO), ''), NULLIF(TRIM(N.OBSERVACAOLF), '')) AS OBSERVACAO,
        NVL(I.VLRITEM, 0) AS VLRITEM,
        NVL(I.VLRIPI, 0) AS VLRIPI,
        NVL(I.VLRICMSST, 0) AS VLRICMSST,
        NVL(N.VLRTOTAL, 0) AS VLRTOTAL,
        I.SEQPRODUTO,
        P.DESCCOMPLETA,
        ROW_NUMBER() OVER (PARTITION BY N.NROEMPRESA, N.SEQNF, N.TIPNOTAFISCAL ORDER BY I.SEQPRODUTO) AS RN_ITEM,
        COUNT(*) OVER (PARTITION BY N.NROEMPRESA, N.SEQNF, N.TIPNOTAFISCAL) AS QTD_ITENS_NF
    FROM MLFV_BASENFE N
    JOIN MFLV_BASEDFITEM I
        ON I.SEQNF = N.SEQNF
       AND I.NROEMPRESA = N.NROEMPRESA
       AND I.TIPNOTAFISCAL = N.TIPNOTAFISCAL
    JOIN MAP_PRODUTO P
        ON P.SEQPRODUTO = I.SEQPRODUTO
    LEFT JOIN GE_PESSOA F
        ON F.SEQPESSOA = N.SEQPESSOA
    LEFT JOIN REDE_FORNEC RF
        ON RF.SEQPESSOA = N.SEQPESSOA
    WHERE (:NR1 = 0 OR N.SEQPESSOA = :NR1)
      AND N.TIPNOTAFISCAL = 'S'
      AND I.TIPNOTAFISCAL = 'S'
      AND N.CODGERALOPER IN (802, 860)
      AND I.CODGERALOPER IN (802, 860)
      AND N.DTAEMISSAO >= TRUNC(:DT1)
      AND N.DTAEMISSAO < TRUNC(:DT2) + 1
      AND I.DTAEMISSAO >= TRUNC(:DT1)
      AND I.DTAEMISSAO < TRUNC(:DT2) + 1
      AND N.STATUSNF != 'C'
      AND NVL(I.STATUSITEM, 'V') != 'C'
      AND N.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18, 50)
      AND (
          :LS1 = ' TODAS AS REDES'
          OR NVL(TRIM(:LS1), 'TODOS') IN ('TODOS', '0 - TODOS', '0', '', ' TODAS AS REDES', 'TODAS AS REDES')
          OR UPPER(TRIM(RF.REDE)) = UPPER(TRIM(:LS1))
      )
), DADOS_NF AS (
    SELECT /*+ MATERIALIZE */
        B.NROEMPRESA,
        B.NUMERONF,
        B.SEQNF,
        B.TIPNOTAFISCAL,
        B.SEQPESSOA,
        B.FORNECEDOR,
        B.REDE,
        B.DTAEMISSAO,
        MAX(B.OBSERVACAO) AS OBSERVACAO,
        SUM(B.VLRITEM) AS VALOR_TOTAL_SEM_IMPOSTOS_NUM,
        SUM(B.VLRITEM + B.VLRIPI + B.VLRICMSST) AS VALOR_TOTAL_COM_IMPOSTOS_NUM,
        MAX(B.VLRTOTAL) AS VALOR_LIQUIDO_NF_NUM,
        LISTAGG(CASE WHEN B.RN_ITEM <= 120 THEN TO_CHAR(B.SEQPRODUTO) END, ' / ') WITHIN GROUP (ORDER BY B.RN_ITEM)
            || CASE WHEN MAX(B.QTD_ITENS_NF) > 120 THEN ' ... (+' || TO_CHAR(MAX(B.QTD_ITENS_NF) - 120) || ')' ELSE '' END AS CODIGOS_PRODUTOS,
        LISTAGG(CASE WHEN B.RN_ITEM <= 45 THEN SUBSTR(B.DESCCOMPLETA, 1, 55) END, ' / ') WITHIN GROUP (ORDER BY B.RN_ITEM)
            || CASE WHEN MAX(B.QTD_ITENS_NF) > 45 THEN ' ... (+' || TO_CHAR(MAX(B.QTD_ITENS_NF) - 45) || ' ITENS)' ELSE '' END AS DESCRICOES_PRODUTOS
    FROM ITENS_BASE B
    GROUP BY
        B.NROEMPRESA,
        B.NUMERONF,
        B.SEQNF,
        B.TIPNOTAFISCAL,
        B.SEQPESSOA,
        B.FORNECEDOR,
        B.REDE,
        B.DTAEMISSAO
    HAVING (
        NVL(TRIM(:LT1), '0') IN ('0', 'TODOS', 'TODAS', '')
        OR INSTR('|' || TRIM('|' FROM REGEXP_REPLACE(:LT1, '[^0-9]+', '|')) || '|', '|' || TO_CHAR(B.NUMERONF) || '|') > 0
        OR REGEXP_LIKE(
            MAX(B.OBSERVACAO),
            '(^|[^0-9])(' || TRIM('|' FROM REGEXP_REPLACE(:LT1, '[^0-9]+', '|')) || ')([^0-9]|$)'
        )
    )
), BOLETOS_NF AS (
    SELECT /*+ MATERIALIZE */
        TF.NROEMPRESA,
        TF.NRODOCUMENTO,
        SUM(NVL(TF.VLRORIGINAL, 0)) AS VALOR_BOLETO_NUM
    FROM MRL_TITULOFIN TF
    JOIN DADOS_NF D
        ON D.NROEMPRESA = TF.NROEMPRESA
       AND D.NUMERONF = TF.NRODOCUMENTO
    JOIN MRL_FORMAPAGTO FP
        ON FP.NROFORMAPAGTO = TF.NROFORMAPAGTO
    JOIN MRL_PARAMCOBRANCA PC
        ON PC.NROEMPRESA = NVL(TF.NROEMPRESACOBR, TF.NROEMPRESA)
       AND PC.NROBANCO = TF.NROBANCO
       AND PC.NROCARTEIRACOBR = TF.NROCARTEIRACOBR
       AND PC.SEQCTACORRENTE = TF.SEQCTACORRENTE
    WHERE NVL(PC.INDEMITEBOLETO, 'S') = 'S'
      AND FP.ESPECIEFORMAPAGTO = 'B'
      AND TF.OBRIGDIREITO = 'D'
      AND NVL(TF.SERIEDOC, '0') != 'OE'
      AND NVL(TF.STATUSTITULOFIN, 'V') != 'C'
      AND NVL(TF.INDEXPORTACAO, 'N') != 'C'
      AND TF.TITULOEMITIDO LIKE 'S%'
    GROUP BY
        TF.NROEMPRESA,
        TF.NRODOCUMENTO
), FINANCEIRO_NF AS (
    SELECT /*+ MATERIALIZE */
        D.NROEMPRESA,
        D.NUMERONF,
        D.SEQPESSOA,
        MIN(T.ABERTOQUITADO) AS ABERTOQUITADO
    FROM FI_TITULO T
    JOIN DADOS_NF D
        ON T.NRODOCUMENTO = D.NUMERONF
       AND T.SEQPESSOA = D.SEQPESSOA
    WHERE T.SITUACAO != 'C'
      AND (T.NROEMPRESA = D.NROEMPRESA OR T.NROEMPRESA IN (1, 3, 15, 50, 900))
    GROUP BY
        D.NROEMPRESA,
        D.NUMERONF,
        D.SEQPESSOA
)
SELECT
    D.NROEMPRESA AS LOJA,
    D.NUMERONF AS NF,
    D.REDE,
    D.SEQPESSOA AS CODIGO_FORNECEDOR,
    D.FORNECEDOR,
    TO_CHAR(D.DTAEMISSAO, 'DD/MM/YYYY') AS DATA_EMISSAO,
    'R$ ' || TO_CHAR(ROUND(D.VALOR_TOTAL_SEM_IMPOSTOS_NUM, 2), 'FM999G999G990D00') AS VALOR_TOTAL_SEM_IMPOSTOS,
    'R$ ' || TO_CHAR(ROUND(D.VALOR_TOTAL_COM_IMPOSTOS_NUM, 2), 'FM999G999G990D00') AS VALOR_TOTAL_COM_IMPOSTOS,
    'R$ ' || TO_CHAR(
        ROUND(
            CASE
                WHEN NVL(B.VALOR_BOLETO_NUM, 0) > 0 AND D.VALOR_TOTAL_COM_IMPOSTOS_NUM > B.VALOR_BOLETO_NUM
                    THEN D.VALOR_TOTAL_COM_IMPOSTOS_NUM - B.VALOR_BOLETO_NUM
                WHEN D.VALOR_LIQUIDO_NF_NUM > 0 AND D.VALOR_TOTAL_COM_IMPOSTOS_NUM > D.VALOR_LIQUIDO_NF_NUM
                    THEN D.VALOR_TOTAL_COM_IMPOSTOS_NUM - D.VALOR_LIQUIDO_NF_NUM
                ELSE 0
            END,
            2
        ),
        'FM999G999G990D00'
    ) AS VALOR_DESCONTO_ACORDO_NF,
    'R$ ' || TO_CHAR(ROUND(D.VALOR_LIQUIDO_NF_NUM, 2), 'FM999G999G990D00') AS VALOR_LIQUIDO_NF,
    'R$ ' || TO_CHAR(ROUND(NVL(B.VALOR_BOLETO_NUM, 0), 2), 'FM999G999G990D00') AS VALOR_DO_BOLETO,
    CASE
        WHEN FIN.ABERTOQUITADO IS NOT NULL THEN FIN.ABERTOQUITADO
        WHEN NVL(B.VALOR_BOLETO_NUM, 0) > 0 THEN 'A'
        ELSE '--'
    END AS ABERTO_QUITADO,
    D.OBSERVACAO,
    D.CODIGOS_PRODUTOS,
    D.DESCRICOES_PRODUTOS
FROM DADOS_NF D
LEFT JOIN BOLETOS_NF B
    ON B.NROEMPRESA = D.NROEMPRESA
   AND B.NRODOCUMENTO = D.NUMERONF
LEFT JOIN FINANCEIRO_NF FIN
    ON FIN.NROEMPRESA = D.NROEMPRESA
   AND FIN.NUMERONF = D.NUMERONF
   AND FIN.SEQPESSOA = D.SEQPESSOA
ORDER BY
    D.DTAEMISSAO,
    D.NUMERONF
)
