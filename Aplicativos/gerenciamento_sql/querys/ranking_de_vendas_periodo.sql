SELECT * FROM (
    WITH CTE_CATEGORIAS AS (
        SELECT /*+ MATERIALIZE */
            X.SEQFAMILIA,
            MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.SEQCATEGORIA END) AS SEQDEPARTAMENTO,
            MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END) AS DEPARTAMENTO,
            COALESCE(
                MAX(CASE WHEN Y.NIVELHIERARQUIA = 4 THEN Y.CATEGORIA END),
                MAX(CASE WHEN Y.NIVELHIERARQUIA = 3 THEN Y.CATEGORIA END),
                MAX(CASE WHEN Y.NIVELHIERARQUIA = 5 THEN Y.CATEGORIA END),
                MAX(CASE WHEN Y.NIVELHIERARQUIA = 2 THEN Y.CATEGORIA END),
                'SEM SUBGRUPO'
            ) AS SUBGRUPO
        FROM MAP_FAMDIVCATEG X
        INNER JOIN MAP_CATEGORIA Y
            ON Y.SEQCATEGORIA = X.SEQCATEGORIA
           AND Y.NRODIVISAO = X.NRODIVISAO
        WHERE Y.TIPCATEGORIA = 'M'
          AND Y.NIVELHIERARQUIA IN (1, 2, 3, 4, 5)
          AND Y.STATUSCATEGOR = 'A'
          AND X.STATUS = 'A'
          AND X.NRODIVISAO = 1
        GROUP BY X.SEQFAMILIA
        HAVING MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END) IS NOT NULL
           AND UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) NOT LIKE '%ALMOX%'
           AND UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) NOT LIKE '%SERVI%'
           AND UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) NOT LIKE '%INATIV%'
           AND UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) NOT LIKE '%CLASSIFICAR%'
           AND UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) NOT LIKE '%IMOBILIZ%'
           AND UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) NOT LIKE '%CONSUMO%'
           AND REPLACE(UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)), 'Í', 'I') NOT LIKE '%PERECIV%'
           AND NVL(REPLACE(UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 2 THEN Y.CATEGORIA END)), '_', ' '), ' ') NOT IN ('FRUTAS E VERDURAS', 'PADARIA BAKLIZI', 'PADARIA INDUSTRIAL', 'ACOUGUE', 'FIAMBRERIA')
    ),
    CTE_PRODUTOS_VALIDOS AS (
        SELECT /*+ MATERIALIZE */
            A.SEQPRODUTO,
            A.SEQFAMILIA,
            A.DESCCOMPLETA AS DESCRICAO,
            CAT.SEQDEPARTAMENTO,
            CAT.DEPARTAMENTO,
            CAT.SUBGRUPO,
            NVL(COMP.COMPRADOR, 'SEM COMPRADOR') AS COMPRADOR
        FROM MAP_PRODUTO A
        INNER JOIN CTE_CATEGORIAS CAT
            ON CAT.SEQFAMILIA = A.SEQFAMILIA
        INNER JOIN MAP_FAMDIVISAO FD
            ON FD.SEQFAMILIA = A.SEQFAMILIA
           AND FD.NRODIVISAO = 1
        LEFT JOIN MAX_COMPRADOR COMP
            ON COMP.SEQCOMPRADOR = FD.SEQCOMPRADOR
        WHERE FD.FINALIDADEFAMILIA = 'R'
          AND (
              NVL(TRIM(:LS1), '0 - TODOS') IN ('0 - TODOS', '0', 'TODOS', '')
              OR (
                  INSTR(:LS1, ' - ') > 0
                  AND CAT.SEQDEPARTAMENTO = TO_NUMBER(SUBSTR(:LS1, 1, INSTR(:LS1, ' - ') - 1))
              )
              OR CAT.SEQDEPARTAMENTO = TO_NUMBER(REGEXP_SUBSTR(:LS1, '^[0-9]+'))
              OR UPPER(TRIM(CAT.DEPARTAMENTO)) = UPPER(TRIM(:LS1))
          )
          AND (
              NVL(TRIM(:NR1), '0') IN ('0', '')
              OR TO_NUMBER(NVL(TRIM(:NR1), '0')) = 0
              OR EXISTS (
                  SELECT 1
                  FROM MAP_FAMFORNEC F
                  WHERE F.SEQFAMILIA = A.SEQFAMILIA
                    AND F.SEQFORNECEDOR = TO_NUMBER(:NR1)
              )
          )
    ),
    CTE_VENDAS AS (
        SELECT /*+ MATERIALIZE */
            C.SEQPRODUTO,
            SUM(NVL(C.VLRTOTALVDA, 0)) AS VALOR_VENDIDO
        FROM MRL_CUSTODIA C
        INNER JOIN CTE_PRODUTOS_VALIDOS PV
            ON PV.SEQPRODUTO = C.SEQPRODUTO
        WHERE C.DTAENTRADASAIDA >= TRUNC(SYSDATE) - CASE
                  WHEN NVL(TO_NUMBER(REGEXP_SUBSTR(TO_CHAR(:NR2), '^[0-9]+')), 0) <= 0 THEN 30
                  ELSE TO_NUMBER(REGEXP_SUBSTR(TO_CHAR(:NR2), '^[0-9]+'))
              END
          AND C.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
        GROUP BY C.SEQPRODUTO
        HAVING SUM(NVL(C.VLRTOTALVDA, 0)) > 0
    ),
    CTE_PRODUTOS AS (
        SELECT /*+ MATERIALIZE */
            PV.COMPRADOR,
            PV.DEPARTAMENTO,
            PV.SUBGRUPO,
            PV.SEQPRODUTO AS SEQCODIGO,
            PV.DESCRICAO,
            V.VALOR_VENDIDO,
            CASE
                WHEN EXISTS (
                    SELECT 1
                    FROM MRL_PRODUTOEMPRESA PE
                    WHERE PE.SEQPRODUTO = PV.SEQPRODUTO
                      AND PE.STATUSCOMPRA = 'A'
                      AND PE.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
                ) THEN 'A'
                ELSE 'I'
            END AS STATUS_COMPRA
        FROM CTE_VENDAS V
        INNER JOIN CTE_PRODUTOS_VALIDOS PV
            ON PV.SEQPRODUTO = V.SEQPRODUTO
    ),
    CTE_RANKING AS (
        SELECT /*+ MATERIALIZE */
            P.COMPRADOR,
            P.DEPARTAMENTO,
            P.SUBGRUPO,
            P.SEQCODIGO,
            P.DESCRICAO,
            P.STATUS_COMPRA,
            P.VALOR_VENDIDO,
            SUM(P.VALOR_VENDIDO) OVER (
                PARTITION BY P.DEPARTAMENTO
                ORDER BY P.VALOR_VENDIDO DESC, P.SEQCODIGO ASC
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ) AS SOMA_ACUMULADA,
            SUM(P.VALOR_VENDIDO) OVER (
                PARTITION BY P.DEPARTAMENTO
            ) AS SOMA_TOTAL
        FROM CTE_PRODUTOS P
    )
    SELECT
        R.COMPRADOR AS COMPRADOR,
        R.DEPARTAMENTO AS DEPARTAMENTO,
        R.SUBGRUPO AS SUBGRUPO,
        R.SEQCODIGO AS SEQCODIGO,
        R.DESCRICAO AS DESCRICAO,
        R.STATUS_COMPRA AS STATUS_COMPRA,
        ROUND(R.VALOR_VENDIDO, 2) AS VALOR_VENDIDO,
        ROUND((R.VALOR_VENDIDO / NULLIF(R.SOMA_TOTAL, 0)) * 100, 2) AS PERC_PARTICIPACAO,
        ROUND((R.SOMA_ACUMULADA / NULLIF(R.SOMA_TOTAL, 0)) * 100, 2) AS PERC_ACUMULADO,
        CASE
            WHEN (R.SOMA_ACUMULADA / NULLIF(R.SOMA_TOTAL, 0)) <= 0.500001 THEN 'A'
            WHEN (R.SOMA_ACUMULADA / NULLIF(R.SOMA_TOTAL, 0)) <= 0.900001 THEN 'B'
            ELSE 'C'
        END AS RANK
    FROM CTE_RANKING R
)
ORDER BY DEPARTAMENTO ASC, VALOR_VENDIDO DESC, SEQCODIGO ASC
