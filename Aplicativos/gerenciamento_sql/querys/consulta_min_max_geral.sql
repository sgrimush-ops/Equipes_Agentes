SELECT * FROM (
WITH FAMILIAS_VALIDAS AS (
    SELECT /*+ MATERIALIZE */
        X.SEQFAMILIA,
        MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN REPLACE(Y.CATEGORIA, '_', ' ') END) AS DEPARTAMENTO
    FROM MAP_FAMDIVCATEG X
    INNER JOIN MAP_CATEGORIA Y ON Y.SEQCATEGORIA = X.SEQCATEGORIA AND Y.NRODIVISAO = X.NRODIVISAO
    WHERE X.NRODIVISAO = 1
      AND X.STATUS = 'A'
      AND Y.NRODIVISAO = 1
      AND Y.STATUSCATEGOR = 'A'
    GROUP BY X.SEQFAMILIA
    HAVING MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END) IS NOT NULL
       AND (
           UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)) IN ('BEBIDAS', 'MERCEARIA', 'PERFUMARIA E LIMPEZA', 'PRODUTOS PET')
           OR MAX(CASE WHEN UPPER(Y.CATEGORIA) LIKE '%LEITE%' OR UPPER(Y.CATEGORIA) LIKE '%CARV%O%' THEN 1 ELSE 0 END) = 1
           OR (
               REPLACE(REPLACE(UPPER(MAX(CASE WHEN Y.NIVELHIERARQUIA = 1 THEN Y.CATEGORIA END)), '_', ' '), 'Í', 'I') IN ('PERECIVEL', 'PERECIVEIS')
               AND MAX(CASE WHEN Y.NIVELHIERARQUIA = 2 AND REPLACE(UPPER(Y.CATEGORIA), '_', ' ') IN ('FRUTAS E VERDURAS', 'PADARIA BAKLIZI', 'PADARIA INDUSTRIAL') THEN 1 ELSE 0 END) = 0
           )
       )
),
PRODUTOS_BASE AS (
    SELECT /*+ MATERIALIZE */
        A.SEQPRODUTO,
        A.SEQFAMILIA,
        A.DESCCOMPLETA,
        A.DTAHORINCLUSAO,
        FV.DEPARTAMENTO,
        FD.FORMAABASTECIMENTO,
        FD.PADRAOEMBCOMPRA,
        FD.PADRAOEMBTRANSF,
        NVL(COMP.COMPRADOR, 'SEM GESTOR') AS COMPRADOR
    FROM MAP_PRODUTO A
    INNER JOIN FAMILIAS_VALIDAS FV ON FV.SEQFAMILIA = A.SEQFAMILIA
    INNER JOIN MAP_FAMDIVISAO FD ON FD.SEQFAMILIA = A.SEQFAMILIA AND FD.NRODIVISAO = 1
    LEFT JOIN MAX_COMPRADOR COMP ON COMP.SEQCOMPRADOR = FD.SEQCOMPRADOR
    WHERE FD.FINALIDADEFAMILIA = 'R'
      AND EXISTS (
          SELECT 1
          FROM MRL_PRODUTOEMPRESA PE
          WHERE PE.SEQPRODUTO = A.SEQPRODUTO
            AND PE.STATUSCOMPRA = 'A'
            AND PE.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
      )
),
PEND_COMPRA AS (
    SELECT /*+ MATERIALIZE */
        R.SEQPRODUTO,
        R.NROEMPRESA,
        NVL(SUM(CASE WHEN NVL(R.QTDSOLICITADA, 0) > NVL(R.QTDRECCANC, 0) THEN NVL(R.QTDSOLICITADA, 0) - NVL(R.QTDRECCANC, 0) ELSE 0 END), 0) AS QTD
    FROM MAXV_MSUPEDIDOSUPRIMREC R
    INNER JOIN PRODUTOS_BASE PB ON PB.SEQPRODUTO = R.SEQPRODUTO
    WHERE R.TIPPEDIDOSUPRIM = 'C'
      AND R.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
    GROUP BY R.SEQPRODUTO, R.NROEMPRESA
),
PEND_TRANSF AS (
    SELECT /*+ MATERIALIZE */
        E.SEQPRODUTO,
        E.NROEMPDESTINO,
        NVL(SUM(NVL(E.QTDSOLICITADA, 0) - NVL(E.QTDEXPCANC, 0)), 0) AS QTD
    FROM MAXV_MSUPEDIDOSUPRIMEXP E
    INNER JOIN PRODUTOS_BASE PB ON PB.SEQPRODUTO = E.SEQPRODUTO
    WHERE E.NROEMPRESA IN (15, 16, 50)
      AND E.NROEMPDESTINO IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
    GROUP BY E.SEQPRODUTO, E.NROEMPDESTINO
),
TRANSITO AS (
    SELECT /*+ MATERIALIZE */
        R.SEQPRODUTO,
        R.NROEMPRESA,
        NVL(SUM(NVL(R.QTDTOTTRANSITO, 0)), 0) AS QTD
    FROM MSU_PSITEMRECEBER R
    INNER JOIN PRODUTOS_BASE PB ON PB.SEQPRODUTO = R.SEQPRODUTO
    INNER JOIN MSU_PEDIDOSUPRIM PS ON PS.NROPEDIDOSUPRIM = R.NROPEDIDOSUPRIM AND PS.NROEMPRESA = R.NROEMPRESA
    WHERE PS.SEQFORNECEDOR IN (15, 16, 50)
      AND R.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
    GROUP BY R.SEQPRODUTO, R.NROEMPRESA
),
VENDAS AS (
    SELECT /*+ MATERIALIZE */
        C.SEQPRODUTO,
        C.NROEMPRESA,
        PB.DEPARTAMENTO,
        ROUND(NVL(SUM(C.QTDVDA), 0), 2) AS QTD,
        NVL(SUM(C.VLRTOTALVDA), 0) AS VLR_VENDA
    FROM MRL_CUSTODIA C
    INNER JOIN PRODUTOS_BASE PB ON PB.SEQPRODUTO = C.SEQPRODUTO
    WHERE C.DTAENTRADASAIDA >= TRUNC(SYSDATE) - NVL(:NR1, 90)
      AND C.DTAENTRADASAIDA < TRUNC(SYSDATE)
      AND C.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
    GROUP BY C.SEQPRODUTO, C.NROEMPRESA, PB.DEPARTAMENTO
),
RANKING_ABC AS (
    SELECT /*+ MATERIALIZE */
        RC.SEQPRODUTO,
        CASE
            WHEN RC.RN_DEPTO = 1 OR (RC.SOMA_ACUMULADA / NULLIF(RC.SOMA_TOTAL, 0)) <= 0.250001 THEN 'A+'
            WHEN (RC.SOMA_ACUMULADA / NULLIF(RC.SOMA_TOTAL, 0)) <= 0.500001 THEN 'A-'
            WHEN (RC.SOMA_ACUMULADA / NULLIF(RC.SOMA_TOTAL, 0)) <= 0.700001 THEN 'B+'
            WHEN (RC.SOMA_ACUMULADA / NULLIF(RC.SOMA_TOTAL, 0)) <= 0.900001 THEN 'B-'
            WHEN (RC.SOMA_ACUMULADA / NULLIF(RC.SOMA_TOTAL, 0)) <= 0.950001 THEN 'C+'
            ELSE 'C-'
        END AS RANK
    FROM (
        SELECT
            V.SEQPRODUTO,
            ROW_NUMBER() OVER (
                PARTITION BY V.DEPARTAMENTO
                ORDER BY SUM(V.VLR_VENDA) DESC, V.SEQPRODUTO ASC
            ) AS RN_DEPTO,
            SUM(SUM(V.VLR_VENDA)) OVER (
                PARTITION BY V.DEPARTAMENTO
                ORDER BY SUM(V.VLR_VENDA) DESC, V.SEQPRODUTO ASC
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ) AS SOMA_ACUMULADA,
            SUM(SUM(V.VLR_VENDA)) OVER (
                PARTITION BY V.DEPARTAMENTO
            ) AS SOMA_TOTAL
        FROM VENDAS V
        GROUP BY V.SEQPRODUTO, V.DEPARTAMENTO
        HAVING SUM(V.VLR_VENDA) > 0
    ) RC
),
PONTO_EXTRA AS (
    SELECT /*+ MATERIALIZE */
        PEPE.SEQPRODUTO,
        PEPE.NROEMPRESA,
        NVL(SUM(PEPE.ESTQMINIMO), 0) AS ESTQMINIMO_PE,
        NVL(SUM(PEPE.ESTQMAXIMO), 0) AS ESTQMAXIMO_PE
    FROM MRL_PONTOEXTRA PE
    INNER JOIN MRL_PONTOEXTRAPRODUTO PEP ON PEP.SEQPONTOEXTRA = PE.SEQPONTOEXTRA
    INNER JOIN MRL_PONTOEXTRAPRODUTOEMPRESA PEPE ON PEPE.SEQPONTOEXTRA = PEP.SEQPONTOEXTRA AND PEPE.SEQPRODUTO = PEP.SEQPRODUTO
    INNER JOIN PRODUTOS_BASE PB ON PB.SEQPRODUTO = PEPE.SEQPRODUTO
    WHERE PE.STATUS = 'A'
      AND PEPE.STATUS = 'A'
      AND TRUNC(SYSDATE) BETWEEN TRUNC(PEPE.DTAVIGENCIAINICIO) AND TRUNC(PEPE.DTAVIGENCIAFIM)
      AND PEPE.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
    GROUP BY PEPE.SEQPRODUTO, PEPE.NROEMPRESA
),
FORN_PRINCIPAL AS (
    SELECT /*+ MATERIALIZE */
        F.SEQFAMILIA,
        MAX(F.SEQFORNECEDOR) AS COD_FORN_PRINCIPAL,
        MAX(P.NOMERAZAO) AS RAZAO_FORN_PRINCIPAL
    FROM MAP_FAMFORNEC F
    INNER JOIN FAMILIAS_VALIDAS FV ON FV.SEQFAMILIA = F.SEQFAMILIA
    INNER JOIN GE_PESSOA P ON P.SEQPESSOA = F.SEQFORNECEDOR
    WHERE F.PRINCIPAL = 'S'
    GROUP BY F.SEQFAMILIA
)
SELECT
    PB.DEPARTAMENTO AS DEPARTAMENTO,
    PB.COMPRADOR AS COMPRADOR,
    Y.NROEMPRESA AS CODIGO_EMPRESA,
    PB.SEQPRODUTO AS CODIGO_PRODUTO,
    PB.DESCCOMPLETA AS DESCRICAO_PRODUTO,
    NVL(RK.RANK, 'C-') AS RANK,
    PB.FORMAABASTECIMENTO AS FORMA_ABASTECIMENTO,
    TO_CHAR(TRUNC(PB.DTAHORINCLUSAO), 'DD/MM/YYYY') AS DATA_CADASTRO_PRODUTO,
    CASE WHEN Y.STATUSCOMPRA = 'A' THEN 'Ativo' ELSE 'Inativo' END AS STATUS_COMPRA,
    PB.PADRAOEMBCOMPRA AS EMBL_COMPRA,
    PB.PADRAOEMBTRANSF AS EMBL_TRANSFERENCIA,
    (NVL(Y.ESTQLOJA, 0) + NVL(Y.ESTQDEPOSITO, 0) - NVL(Y.QTDRESERVADAVDA, 0) - NVL(Y.QTDRESERVADARECEB, 0)) AS QUANTIDADE_DISPONIVEL,
    NVL(PC.QTD, 0) AS QTD_PEND_PEDCOMPRA,
    NVL(PT.QTD, 0) AS QTD_PEND_PEDTRANSF,
    NVL(TR.QTD, 0) AS QTD_EM_TRANSITO,
    NVL(V.QTD, 0) AS QTD_VENDIDA_PERIODO,
    NVL(Y.ESTQMINIMOLOJA, 0) AS QUANTIDADE_ESTOQUE_MINIMO,
    NVL(Y.ESTQMAXIMOLOJA, 0) AS QUANTIDADE_ESTOQUE_MAXIMO,
    NVL(PX.ESTQMINIMO_PE, 0) AS MINIMO_PONTO_EXTRA,
    NVL(PX.ESTQMAXIMO_PE, 0) AS MAXIMO_PONTO_EXTRA,
    NVL(:NR1, 90) AS DIAS_PESQUISA,
    NVL(FP.COD_FORN_PRINCIPAL, 0) AS COD_FORNECEDOR,
    NVL(FP.RAZAO_FORN_PRINCIPAL, 'SEM FORNECEDOR PRINCIPAL') AS FORNECEDOR
FROM PRODUTOS_BASE PB
INNER JOIN MRL_PRODUTOEMPRESA Y ON PB.SEQPRODUTO = Y.SEQPRODUTO
LEFT JOIN RANKING_ABC RK ON RK.SEQPRODUTO = PB.SEQPRODUTO
LEFT JOIN PEND_COMPRA PC ON PC.SEQPRODUTO = PB.SEQPRODUTO AND PC.NROEMPRESA = Y.NROEMPRESA
LEFT JOIN PEND_TRANSF PT ON PT.SEQPRODUTO = PB.SEQPRODUTO AND PT.NROEMPDESTINO = Y.NROEMPRESA
LEFT JOIN TRANSITO TR ON TR.SEQPRODUTO = PB.SEQPRODUTO AND TR.NROEMPRESA = Y.NROEMPRESA
LEFT JOIN VENDAS V ON V.SEQPRODUTO = PB.SEQPRODUTO AND V.NROEMPRESA = Y.NROEMPRESA
LEFT JOIN PONTO_EXTRA PX ON PX.SEQPRODUTO = PB.SEQPRODUTO AND PX.NROEMPRESA = Y.NROEMPRESA
LEFT JOIN FORN_PRINCIPAL FP ON FP.SEQFAMILIA = PB.SEQFAMILIA
WHERE Y.STATUSCOMPRA = 'A'
  AND Y.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 16, 17, 18)
)
ORDER BY DEPARTAMENTO, CODIGO_EMPRESA, DESCRICAO_PRODUTO
