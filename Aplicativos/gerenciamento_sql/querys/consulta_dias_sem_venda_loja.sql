SELECT *
FROM (
    WITH CTE_FAM_EXPURGO AS (
        SELECT /*+ MATERIALIZE */ DISTINCT
            FDC2.SEQFAMILIA
        FROM MAP_FAMDIVCATEG FDC2
        INNER JOIN MAP_CATEGORIA C2
            ON C2.SEQCATEGORIA = FDC2.SEQCATEGORIA
           AND C2.NRODIVISAO = 1
           AND C2.STATUSCATEGOR = 'A'
        LEFT JOIN MAP_CATEGORIA PAI
            ON PAI.SEQCATEGORIA = C2.SEQCATEGORIAPAI
           AND PAI.NRODIVISAO = 1
           AND PAI.NIVELHIERARQUIA = 2
           AND PAI.STATUSCATEGOR = 'A'
        WHERE FDC2.NRODIVISAO = 1
          AND FDC2.STATUS = 'A'
          AND (
              (C2.NIVELHIERARQUIA = 2 AND REPLACE(UPPER(C2.CATEGORIA), '_', ' ') IN ('FRUTAS E VERDURAS', 'PADARIA BAKLIZI', 'PADARIA INDUSTRIAL'))
              OR REPLACE(UPPER(PAI.CATEGORIA), '_', ' ') IN ('FRUTAS E VERDURAS', 'PADARIA BAKLIZI', 'PADARIA INDUSTRIAL')
          )
    ),
    CTE_FAMILIAS_VALIDAS AS (
        SELECT /*+ MATERIALIZE */
            D.SEQFAMILIA,
            C.CATEGORIA AS DEPTO,
            NVL(COMP.APELIDO, COMP.COMPRADOR) AS COMPRADOR,
            CASE D.FORMAABASTECIMENTO
                WHEN 'C' THEN 'M'
                WHEN 'F' THEN 'FORNECEDOR'
                ELSE D.FORMAABASTECIMENTO
            END AS ABAST
        FROM MAP_FAMDIVISAO D
        INNER JOIN MAP_FAMDIVCATEG F
            ON D.SEQFAMILIA = F.SEQFAMILIA
           AND F.NRODIVISAO = 1
           AND F.STATUS = 'A'
        INNER JOIN MAP_CATEGORIA C
            ON F.SEQCATEGORIA = C.SEQCATEGORIA
           AND C.NIVELHIERARQUIA = 1
           AND C.TIPCATEGORIA = 'M'
        LEFT JOIN MAX_COMPRADOR COMP
            ON D.SEQCOMPRADOR = COMP.SEQCOMPRADOR
        WHERE D.NRODIVISAO = 1
          AND D.FINALIDADEFAMILIA = 'R'
          AND UPPER(C.CATEGORIA) NOT LIKE '%ALMOX%'
          AND UPPER(C.CATEGORIA) NOT LIKE '%SERVI%'
          AND UPPER(C.CATEGORIA) NOT LIKE '%ALIMENTO%'
          AND UPPER(C.CATEGORIA) NOT LIKE '%INATIV%'
          AND NOT EXISTS (
              SELECT 1
              FROM CTE_FAM_EXPURGO EXP
              WHERE EXP.SEQFAMILIA = D.SEQFAMILIA
          )
    )
    SELECT
        FAM.DEPTO,
        FAM.COMPRADOR,
        A.SEQPRODUTO AS CODIGO,
        A.DESCCOMPLETA AS DESCRICAO,
        B.NROEMPRESA AS LOJA,
        FAM.ABAST,
        NVL(B.ESTQLOJA, 0) + NVL(B.ESTQDEPOSITO, 0) - NVL(B.QTDRESERVADAVDA, 0) - NVL(B.QTDRESERVADARECEB, 0) AS ESTOQUE,
        TO_CHAR(TRUNC(B.DTAULTVENDA), 'DD/MM/YYYY') AS ULT_VENDA,
        CASE
            WHEN B.DTAULTVENDA IS NOT NULL THEN
                TRUNC(SYSDATE) - TRUNC(B.DTAULTVENDA)
            WHEN (TRUNC(SYSDATE) - TRUNC(A.DTAHORINCLUSAO)) <= NVL(TO_NUMBER(:NR1), 60) AND NVL(B.DTAULTMOVENTRADA, B.DTAULTCOMPRA) IS NOT NULL THEN
                TRUNC(SYSDATE) - TRUNC(NVL(B.DTAULTMOVENTRADA, B.DTAULTCOMPRA))
            WHEN (TRUNC(SYSDATE) - TRUNC(A.DTAHORINCLUSAO)) <= NVL(TO_NUMBER(:NR1), 60) AND NVL(B.DTAULTMOVENTRADA, B.DTAULTCOMPRA) IS NULL THEN
                0
            ELSE
                TRUNC(SYSDATE) - TRUNC(NVL(NVL(B.DTAULTMOVENTRADA, B.DTAULTCOMPRA), A.DTAHORINCLUSAO))
        END AS DIAS_SEM_VDA,
        TO_CHAR(TRUNC(NVL(B.DTAULTMOVENTRADA, B.DTAULTCOMPRA)), 'DD/MM/YYYY') AS ULT_ENTRADA,
        TRUNC(SYSDATE) - TRUNC(NVL(NVL(B.DTAULTMOVENTRADA, B.DTAULTCOMPRA), A.DTAHORINCLUSAO)) AS DIAS_SEM_ENT,
        TO_CHAR(TRUNC(A.DTAHORINCLUSAO), 'DD/MM/YYYY') AS CADASTRO
    FROM CTE_FAMILIAS_VALIDAS FAM
    INNER JOIN MAP_PRODUTO A
        ON A.SEQFAMILIA = FAM.SEQFAMILIA
    INNER JOIN MRL_PRODUTOEMPRESA B
        ON A.SEQPRODUTO = B.SEQPRODUTO
    WHERE A.SEQPRODUTO NOT IN (15762, 15764, 15765)
      AND (',' || REPLACE(:LT1, ' ', '') || ',' LIKE '%,' || B.NROEMPRESA || ',%')
      AND (
          TRIM(:LT4) IS NULL
          OR INSTR(',' || UPPER(REPLACE(:LT4, ' ', '')) || ',', ',' || UPPER(TRIM(B.STATUSCOMPRA)) || ',') > 0
      )
)
WHERE ESTOQUE <> 0
  AND (
    TRIM(:LT2) IS NULL
    OR ( :LT2 LIKE '>%'  AND :LT2 NOT LIKE '>=%' AND DIAS_SEM_VDA >  TO_NUMBER(REGEXP_REPLACE(:LT2, '[^0-9-]', '')) )
    OR ( :LT2 LIKE '<%'  AND :LT2 NOT LIKE '<=%' AND DIAS_SEM_VDA <  TO_NUMBER(REGEXP_REPLACE(:LT2, '[^0-9-]', '')) )
    OR ( :LT2 LIKE '=%'  AND DIAS_SEM_VDA =  TO_NUMBER(REGEXP_REPLACE(:LT2, '[^0-9-]', '')) )
    OR ( :LT2 LIKE '>=%' AND DIAS_SEM_VDA >= TO_NUMBER(REGEXP_REPLACE(:LT2, '[^0-9-]', '')) )
    OR ( :LT2 LIKE '<=%' AND DIAS_SEM_VDA <= TO_NUMBER(REGEXP_REPLACE(:LT2, '[^0-9-]', '')) )
    OR ( :LT2 NOT LIKE '<%' AND :LT2 NOT LIKE '>%' AND :LT2 NOT LIKE '=%' AND DIAS_SEM_VDA = TO_NUMBER(REGEXP_REPLACE(:LT2, '[^0-9-]', '')) )
  )
ORDER BY DEPTO ASC, DESCRICAO ASC, LOJA ASC
