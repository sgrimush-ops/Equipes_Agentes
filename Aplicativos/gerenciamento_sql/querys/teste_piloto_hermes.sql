SELECT * FROM (
    WITH BASE_ESTOQUE AS (
        SELECT /*+ MATERIALIZE */
            A.SEQPRODUTO,
            B.DESCCOMPLETA AS DESCRICAO_PRODUTO,
            A.NROEMPRESA AS CODIGO_EMPRESA,
            NVL(A.ESTQLOJA, 0) AS ESTOQUE_LOJA,
            NVL(A.ESTQDEPOSITO, 0) AS ESTOQUE_DEPOSITO,
            (NVL(A.ESTQLOJA, 0) + NVL(A.ESTQDEPOSITO, 0)) AS ESTOQUE_TOTAL,
            NVL(A.DTAULTVENDA, TO_DATE('01/01/2000', 'DD/MM/YYYY')) AS DATA_ULTIMA_VENDA
        FROM MRL_PRODUTOEMPRESA A
        INNER JOIN MAP_PRODUTO B ON B.SEQPRODUTO = A.SEQPRODUTO
        WHERE A.STATUSCOMPRA = 'A'
          AND A.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
          AND (INSTR(',' || UPPER(REPLACE(:LT1, ' ', '')) || ',', ',' || TO_CHAR(A.NROEMPRESA) || ',') > 0 OR :LT1 IS NULL)
          AND (NVL(A.ESTQLOJA, 0) + NVL(A.ESTQDEPOSITO, 0)) >= NVL(:NR1, 0)
    )
    SELECT
        SEQPRODUTO AS CODIGO_PRODUTO,
        DESCRICAO_PRODUTO,
        CODIGO_EMPRESA,
        ESTOQUE_LOJA,
        ESTOQUE_DEPOSITO,
        ESTOQUE_TOTAL,
        TO_CHAR(DATA_ULTIMA_VENDA, 'DD/MM/YYYY') AS DATA_ULTIMA_VENDA
    FROM BASE_ESTOQUE
    ORDER BY ESTOQUE_TOTAL DESC, CODIGO_EMPRESA, DESCRICAO_PRODUTO
)
