SELECT
    'MAD_JUNCAOPEDCLIENTEPALETE' AS FONTE,
    J.NROPEDORIGEM AS PEDIDO_ORIGEM,
    J.NROPEDGERADO AS PEDIDO_GERADO,
    J.NROPEDSUPRIM AS PEDIDO_SUPRIMENTO,
    NULL AS DATA_REFERENCIA,
    J.QTDPEDIDO AS QTDE_REFERENCIA,
    NULL AS PEDIDO_FORNECEDOR
FROM MAD_JUNCAOPEDCLIENTEPALETE J
WHERE J.NROPEDORIGEM IN (31339, 31342)
   OR J.NROPEDGERADO IN (31339, 31342)
   OR J.NROPEDSUPRIM IN (31339, 31342)

UNION ALL

SELECT
    'MACX_IMPABASTECIMENTO' AS FONTE,
    TO_NUMBER(I.NROPEDORIGEM) AS PEDIDO_ORIGEM,
    I.NROPEDGERADO AS PEDIDO_GERADO,
    NULL AS PEDIDO_SUPRIMENTO,
    TO_CHAR(TRUNC(I.DTAPROCPEDIDO), 'DD/MM/YYYY') AS DATA_REFERENCIA,
    NULL AS QTDE_REFERENCIA,
    NULL AS PEDIDO_FORNECEDOR
FROM MACX_IMPABASTECIMENTO I
WHERE REGEXP_LIKE(I.NROPEDORIGEM, '^[0-9]+$')
  AND (TO_NUMBER(I.NROPEDORIGEM) IN (31339, 31342) OR I.NROPEDGERADO IN (31339, 31342))

UNION ALL

SELECT
    'MAC_GERCOMPRAPED' AS FONTE,
    NULL AS PEDIDO_ORIGEM,
    G.NROPEDIDO AS PEDIDO_GERADO,
    NULL AS PEDIDO_SUPRIMENTO,
    TO_CHAR(TRUNC(G.DTARECEBIMENTO), 'DD/MM/YYYY') AS DATA_REFERENCIA,
    NULL AS QTDE_REFERENCIA,
    NULL AS PEDIDO_FORNECEDOR
FROM MAC_GERCOMPRAPED G
WHERE G.NROPEDIDO IN (31339, 31342)

UNION ALL

