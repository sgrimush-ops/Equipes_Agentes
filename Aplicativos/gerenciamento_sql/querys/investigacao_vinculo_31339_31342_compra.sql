SELECT
    'MACV_PSITEMRECEBER' AS FONTE,
    NULL AS PEDIDO_ORIGEM,
    R.NROPEDFORNECEDORNUM AS PEDIDO_GERADO,
    R.NROPEDIDOSUPRIM AS PEDIDO_SUPRIMENTO,
    TO_CHAR(TRUNC(R.DTARECEBTOPED), 'DD/MM/YYYY') AS DATA_REFERENCIA,
    R.QTDRECEBIDA AS QTDE_REFERENCIA,
    R.NROPEDFORNECEDOR AS PEDIDO_FORNECEDOR
FROM MACV_PSITEMRECEBER R
WHERE R.NROPEDIDOSUPRIM IN (31339, 31342)
   OR R.NROPEDFORNECEDORNUM IN (31339, 31342)

UNION ALL

SELECT
    'MACV_PSITEMEXPEDIR' AS FONTE,
    NULL AS PEDIDO_ORIGEM,
    E.NROPEDFORNECEDORNUM AS PEDIDO_GERADO,
    E.NROPEDIDOSUPRIM AS PEDIDO_SUPRIMENTO,
    TO_CHAR(TRUNC(E.DTARECEBTO), 'DD/MM/YYYY') AS DATA_REFERENCIA,
    NULL AS QTDE_REFERENCIA,
    E.NROPEDFORNECEDOR AS PEDIDO_FORNECEDOR
FROM MACV_PSITEMEXPEDIR E
WHERE E.NROPEDIDOSUPRIM IN (31339, 31342)
   OR E.NROPEDFORNECEDORNUM IN (31339, 31342)

UNION ALL

SELECT
    'MAD_PEDVENDACONTROL' AS FONTE,
    C.NROPEDVENDAORIG AS PEDIDO_ORIGEM,
    C.NROPEDVENDANOVO AS PEDIDO_GERADO,
    C.NROPEDEXPEDIR AS PEDIDO_SUPRIMENTO,
    NULL AS DATA_REFERENCIA,
    NULL AS QTDE_REFERENCIA,
    NULL AS PEDIDO_FORNECEDOR
FROM MAD_PEDVENDACONTROL C
WHERE C.NROPEDEXPEDIR IN (31339, 31342)
   OR C.NROPEDVENDAANT IN (31339, 31342)
   OR C.NROPEDVENDANOVO IN (31339, 31342)
   OR C.NROPEDVENDAORIG IN (31339, 31342)

ORDER BY
    FONTE,
    PEDIDO_SUPRIMENTO,
    PEDIDO_ORIGEM,
    PEDIDO_GERADO
