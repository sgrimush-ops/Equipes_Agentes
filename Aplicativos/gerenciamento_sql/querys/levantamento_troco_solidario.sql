SELECT *
FROM (
    WITH CTE_PDV_TS AS (
        SELECT /*+ MATERIALIZE */
            TS.NROEMPRESA,
            TS.NROCHECKOUT,
            TS.SEQDOCTO,
            TRUNC(D.DTAMOVIMENTO) AS DTAMOVIMENTO,
            D.COO AS NRO_COMPROVANTE,
            D.SEQUSUARIO AS SEQ_OPERADOR,
            TS.SEQPESSOA AS SEQ_INSTITUICAO,
            SUM(NVL(P.VLRTOTAL, NVL(P.VALOR, 0))) AS VLR_DOADO
        FROM CONSINCOMONITOR.TB_DOCTOTROCOSOLIDARIO TS
        INNER JOIN CONSINCOMONITOR.TB_DOCTO D
            ON D.NROEMPRESA = TS.NROEMPRESA
           AND D.NROCHECKOUT = TS.NROCHECKOUT
           AND D.SEQDOCTO = TS.SEQDOCTO
        INNER JOIN CONSINCOMONITOR.TB_DOCTOPAGTO P
            ON P.NROEMPRESA = TS.NROEMPRESA
           AND P.NROCHECKOUT = TS.NROCHECKOUT
           AND P.SEQDOCTO = TS.SEQDOCTO
        LEFT JOIN CONSINCOMONITOR.TB_DOCTOESTORNO EST
            ON EST.NROEMPRESA = TS.NROEMPRESA
           AND EST.NROCHECKOUT = TS.NROCHECKOUT
           AND EST.SEQDOCTO = TS.SEQDOCTO
        WHERE D.DTAMOVIMENTO >= TRUNC(:DT1)
          AND D.DTAMOVIMENTO <= TRUNC(:DT2)
          AND TS.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
          AND (
              NVL(UPPER(TRIM(:LT1)), '0') IN ('0', 'TODAS', 'TODOS')
              OR INSTR(',' || REPLACE(:LT1, ' ', '') || ',', ',' || TO_CHAR(TS.NROEMPRESA) || ',') > 0
          )
          AND NVL(P.STATUS, 'A') != 'C'
          AND EST.SEQDOCTO IS NULL
        GROUP BY
            TS.NROEMPRESA,
            TS.NROCHECKOUT,
            TS.SEQDOCTO,
            TRUNC(D.DTAMOVIMENTO),
            D.COO,
            D.SEQUSUARIO,
            TS.SEQPESSOA
    ),
    CTE_AGRUPADA AS (
        SELECT /*+ MATERIALIZE */
            U.NROEMPRESA AS LOJA,
            U.SEQ_OPERADOR AS ID_OPERADOR,
            NVL(USU.CODUSUARIO, 'SEM LOGIN') AS LOGIN_OPERADORA,
            NVL(USU.NOME, 'OPERADOR NAO IDENTIFICADO (' || TO_CHAR(U.SEQ_OPERADOR) || ')') AS NOME_OPERADORA,
            U.SEQ_INSTITUICAO AS COD_INSTITUICAO,
            NVL(PES.NOMERAZAO, 'INSTITUICAO NAO IDENTIFICADA') AS INSTITUICAO_BENEFICIADA,
            COUNT(1) AS QTD_DOACOES,
            ROUND(SUM(U.VLR_DOADO), 2) AS VLR_TOTAL_NUM,
            ROUND(AVG(U.VLR_DOADO), 2) AS TICKET_MEDIO_NUM,
            ROUND(MAX(U.VLR_DOADO), 2) AS MAIOR_DOACAO_NUM,
            TO_CHAR(MIN(U.DTAMOVIMENTO), 'DD/MM/YYYY') || ' A ' || TO_CHAR(MAX(U.DTAMOVIMENTO), 'DD/MM/YYYY') AS PERIODO_CAPTURADO
        FROM CTE_PDV_TS U
        LEFT JOIN CONSINCO.GE_USUARIO USU
            ON USU.SEQUSUARIO = U.SEQ_OPERADOR
        LEFT JOIN CONSINCO.GE_PESSOA PES
            ON PES.SEQPESSOA = U.SEQ_INSTITUICAO
        WHERE U.VLR_DOADO > 0
        GROUP BY
            U.NROEMPRESA,
            U.SEQ_OPERADOR,
            NVL(USU.CODUSUARIO, 'SEM LOGIN'),
            NVL(USU.NOME, 'OPERADOR NAO IDENTIFICADO (' || TO_CHAR(U.SEQ_OPERADOR) || ')'),
            U.SEQ_INSTITUICAO,
            NVL(PES.NOMERAZAO, 'INSTITUICAO NAO IDENTIFICADA')
    ),
    CTE_RANKING AS (
        SELECT /*+ MATERIALIZE */
            ROW_NUMBER() OVER (ORDER BY A.VLR_TOTAL_NUM DESC, A.QTD_DOACOES DESC, A.LOJA ASC) AS POSICAO_RANKING,
            A.LOJA,
            A.ID_OPERADOR,
            A.LOGIN_OPERADORA,
            A.NOME_OPERADORA,
            A.COD_INSTITUICAO,
            A.INSTITUICAO_BENEFICIADA,
            A.QTD_DOACOES,
            A.VLR_TOTAL_NUM,
            A.TICKET_MEDIO_NUM,
            A.MAIOR_DOACAO_NUM,
            A.PERIODO_CAPTURADO
        FROM CTE_AGRUPADA A
    )
    SELECT
        CASE
            WHEN G.ORDEM_BLOCO = 2 THEN NULL
            ELSE G.POSICAO_RANKING
        END AS RANKING,
        G.LOJA,
        G.ID_OPERADOR,
        G.LOGIN_OPERADORA,
        G.NOME_OPERADORA,
        G.COD_INSTITUICAO,
        G.INSTITUICAO_BENEFICIADA,
        G.QTD_DOACOES,
        'R$ ' || TO_CHAR(NVL(G.VLR_TOTAL_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS VLR_TOTAL_ARRECADADO,
        'R$ ' || TO_CHAR(NVL(G.TICKET_MEDIO_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS DOACAO_MEDIA,
        'R$ ' || TO_CHAR(NVL(G.MAIOR_DOACAO_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS MAIOR_DOACAO,
        G.PERIODO_CAPTURADO
    FROM (
        SELECT
            1 AS ORDEM_BLOCO,
            R.POSICAO_RANKING,
            R.LOJA,
            R.ID_OPERADOR,
            R.LOGIN_OPERADORA,
            R.NOME_OPERADORA,
            R.COD_INSTITUICAO,
            R.INSTITUICAO_BENEFICIADA,
            R.QTD_DOACOES,
            R.VLR_TOTAL_NUM,
            R.TICKET_MEDIO_NUM,
            R.MAIOR_DOACAO_NUM,
            R.PERIODO_CAPTURADO
        FROM CTE_RANKING R
        UNION ALL
        SELECT
            2 AS ORDEM_BLOCO,
            999999 AS POSICAO_RANKING,
            CAST(NULL AS NUMBER) AS LOJA,
            CAST(NULL AS NUMBER) AS ID_OPERADOR,
            'TOTAL' AS LOGIN_OPERADORA,
            'TOTAL GERAL ->' AS NOME_OPERADORA,
            CAST(NULL AS NUMBER) AS COD_INSTITUICAO,
            'CONSOLIDADO PERIODO' AS INSTITUICAO_BENEFICIADA,
            NVL(SUM(R.QTD_DOACOES), 0) AS QTD_DOACOES,
            ROUND(NVL(SUM(R.VLR_TOTAL_NUM), 0), 2) AS VLR_TOTAL_NUM,
            ROUND(NVL(SUM(R.VLR_TOTAL_NUM) / NULLIF(SUM(R.QTD_DOACOES), 0), 0), 2) AS TICKET_MEDIO_NUM,
            ROUND(NVL(MAX(R.MAIOR_DOACAO_NUM), 0), 2) AS MAIOR_DOACAO_NUM,
            TO_CHAR(TRUNC(:DT1), 'DD/MM/YYYY') || ' A ' || TO_CHAR(TRUNC(:DT2), 'DD/MM/YYYY') AS PERIODO_CAPTURADO
        FROM CTE_RANKING R
    ) G
    ORDER BY
        G.ORDEM_BLOCO ASC,
        G.POSICAO_RANKING ASC
)

