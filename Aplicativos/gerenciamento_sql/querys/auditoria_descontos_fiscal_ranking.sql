SELECT *
FROM (
    WITH CTE_RESUMO_DF_LOJA AS (
        SELECT /*+ MATERIALIZE */
            A.SEQTIPOACRESCDESCTO,
            A.NROEMPRESA,
            COUNT(DISTINCT A.NROEMPRESA || '-' || A.SEQNF) AS QTD_CUPONS,
            COUNT(1) AS QTD_ITENS,
            SUM(NVL(A.VALOR, 0)) AS VLR_TOTAL_DESC,
            MAX(NVL(A.VALOR, 0)) AS MAIOR_DESC
        FROM CONSINCO.MFL_DOCTOFISCAL D
        INNER JOIN CONSINCO.MFL_DFITEMACRESCDESCTO A
            ON A.SEQNF = D.SEQNF
           AND A.NROEMPRESA = D.NROEMPRESA
        WHERE D.DTAMOVIMENTO >= TRUNC(:DT1)
          AND D.DTAMOVIMENTO <= TRUNC(:DT2)
          AND D.STATUSDF != 'C'
          AND A.VALOR > 0
          AND D.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
          AND (
              NVL(UPPER(TRIM(:LT1)), '0') IN ('0', 'TODAS', 'TODOS')
              OR INSTR(',' || REPLACE(:LT1, ' ', '') || ',', ',' || TO_CHAR(D.NROEMPRESA) || ',') > 0
          )
        GROUP BY
            A.SEQTIPOACRESCDESCTO,
            A.NROEMPRESA
    ),
    CTE_RESUMO_DF AS (
        SELECT /*+ MATERIALIZE */
            L.SEQTIPOACRESCDESCTO,
            COUNT(DISTINCT L.NROEMPRESA) AS QTD_LOJAS,
            LISTAGG(TO_CHAR(L.NROEMPRESA), ', ') WITHIN GROUP (ORDER BY L.NROEMPRESA) AS Q_LOJAS,
            SUM(L.QTD_CUPONS) AS QTD_CUPONS,
            SUM(L.QTD_ITENS) AS QTD_ITENS,
            ROUND(SUM(L.VLR_TOTAL_DESC), 2) AS VLR_TOTAL_DESC,
            ROUND(SUM(L.VLR_TOTAL_DESC) / NULLIF(SUM(L.QTD_ITENS), 0), 2) AS MEDIA_DESC,
            ROUND(MAX(L.MAIOR_DESC), 2) AS MAIOR_DESC
        FROM CTE_RESUMO_DF_LOJA L
        GROUP BY
            L.SEQTIPOACRESCDESCTO
    ),
    CTE_LOG_FISCAL_LOJA AS (
        SELECT /*+ MATERIALIZE */
            S.NROEMPRESA,
            COUNT(DISTINCT S.NROEMPRESA || '-' || TO_CHAR(DOC.DTAMOVIMENTO, 'YYYYMMDD') || '-' || DOC.COO) AS QTD_CUPONS_FISC,
            COUNT(1) AS QTD_ITENS_FISC,
            SUM(NVL(V.VALOR, NVL(CF.VLRDESCONTO, 0))) AS VLR_TOTAL_FISC,
            MAX(NVL(V.VALOR, NVL(CF.VLRDESCONTO, 0))) AS MAIOR_FISC
        FROM CONSINCOMONITOR.TB_LOGSEGURANCAPDV S
        INNER JOIN CONSINCOMONITOR.TB_LOGSEGDOCTOPDV DOC
            ON DOC.NROEMPRESA = S.NROEMPRESA
           AND DOC.NROCHECKOUT = S.NROCHECKOUT
           AND DOC.SEQLOGSEGPDV = S.SEQLOGSEGPDV
        LEFT JOIN CONSINCOMONITOR.TB_LOGSEGITEMPDV IT
            ON IT.NROEMPRESA = S.NROEMPRESA
           AND IT.NROCHECKOUT = S.NROCHECKOUT
           AND IT.SEQLOGSEGPDV = S.SEQLOGSEGPDV
        LEFT JOIN CONSINCOMONITOR.TB_LOGSEGVALORPDV V
            ON V.NROEMPRESA = S.NROEMPRESA
           AND V.NROCHECKOUT = S.NROCHECKOUT
           AND V.SEQLOGSEGPDV = S.SEQLOGSEGPDV
        INNER JOIN CONSINCO.MFL_CUPOMFISCAL CF
            ON CF.NROEMPRESA = S.NROEMPRESA
           AND CF.NROCHECKOUT = S.NROCHECKOUT
           AND CF.DTAMOVIMENTO = DOC.DTAMOVIMENTO
           AND CF.NUMERODF = DOC.COO
           AND CF.SEQITEMDF = NVL(IT.SEQITEM, CF.SEQITEMDF)
           AND CF.STATUSCF != 'C'
           AND CF.STATUSITEM != 'C'
        WHERE S.DTAHOREMISSAO >= TRUNC(:DT1)
          AND S.DTAHOREMISSAO < TRUNC(:DT2) + 1
          AND S.NROEMPRESA IN (1, 2, 3, 4, 5, 6, 7, 8, 11, 12, 13, 14, 15, 17, 18)
          AND (
              NVL(UPPER(TRIM(:LT1)), '0') IN ('0', 'TODAS', 'TODOS')
              OR INSTR(',' || REPLACE(:LT1, ' ', '') || ',', ',' || TO_CHAR(S.NROEMPRESA) || ',') > 0
          )
          AND S.METODO = 'mtDescontoItemDiferencaPreco'
        GROUP BY
            S.NROEMPRESA
    ),
    CTE_LOG_FISCAL_ITEM AS (
        SELECT /*+ MATERIALIZE */
            COUNT(DISTINCT FL.NROEMPRESA) AS QTD_LOJAS_FISC,
            NVL(LISTAGG(TO_CHAR(FL.NROEMPRESA), ', ') WITHIN GROUP (ORDER BY FL.NROEMPRESA), '-') AS Q_LOJAS_FISC,
            NVL(SUM(FL.QTD_CUPONS_FISC), 0) AS QTD_CUPONS_FISC,
            NVL(SUM(FL.QTD_ITENS_FISC), 0) AS QTD_ITENS_FISC,
            ROUND(NVL(SUM(FL.VLR_TOTAL_FISC), 0), 2) AS VLR_TOTAL_FISC,
            ROUND(NVL(SUM(FL.VLR_TOTAL_FISC) / NULLIF(SUM(FL.QTD_ITENS_FISC), 0), 0), 2) AS MEDIA_FISC,
            ROUND(NVL(MAX(FL.MAIOR_FISC), 0), 2) AS MAIOR_FISC
        FROM CTE_LOG_FISCAL_LOJA FL
    ),
    CTE_TODAS_LOJAS_ATIVAS AS (
        SELECT /*+ MATERIALIZE */
            COUNT(DISTINCT X.NROEMPRESA) AS QTD_LOJAS_GERAL,
            NVL(LISTAGG(TO_CHAR(X.NROEMPRESA), ', ') WITHIN GROUP (ORDER BY X.NROEMPRESA), '-') AS Q_LOJAS_GERAL
        FROM (
            SELECT DISTINCT NROEMPRESA FROM CTE_RESUMO_DF_LOJA
            UNION
            SELECT DISTINCT NROEMPRESA FROM CTE_LOG_FISCAL_LOJA
        ) X
    ),
    CTE_CONSOLIDADO AS (
        SELECT /*+ MATERIALIZE */
            T.SEQTIPOACRESCDESCTO AS COD_TIPO,
            UPPER(T.TIPOACRESCDESCTO) AS DESCRICAO_TIPO_DESCONTO,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO IN (1, 2, 3) THEN 'MANUAL (FISCAL DE CAIXA)'
                ELSE 'AUTOMATICO (SISTEMA)'
            END AS ORIGEM_DESCONTO,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.QTD_LOJAS_FISC, 0)
                ELSE NVL(R.QTD_LOJAS, 0)
            END AS QTD_LOJAS,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.Q_LOJAS_FISC, '-')
                ELSE NVL(R.Q_LOJAS, '-')
            END AS Q_LOJAS,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.QTD_CUPONS_FISC, 0)
                ELSE NVL(R.QTD_CUPONS, 0)
            END AS QTD_CUPONS_VALIDOS,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.QTD_ITENS_FISC, 0)
                WHEN T.SEQTIPOACRESCDESCTO = 21 AND NVL(R.QTD_ITENS, 0) > NVL(F.QTD_ITENS_FISC, 0) THEN NVL(R.QTD_ITENS, 0) - NVL(F.QTD_ITENS_FISC, 0)
                ELSE NVL(R.QTD_ITENS, 0)
            END AS QTD_ITENS_COM_DESCONTO,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.VLR_TOTAL_FISC, 0)
                WHEN T.SEQTIPOACRESCDESCTO = 21 AND NVL(R.VLR_TOTAL_DESC, 0) > NVL(F.VLR_TOTAL_FISC, 0) THEN ROUND(NVL(R.VLR_TOTAL_DESC, 0) - NVL(F.VLR_TOTAL_FISC, 0), 2)
                ELSE NVL(R.VLR_TOTAL_DESC, 0)
            END AS VLR_DESC_NUM,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.MEDIA_FISC, 0)
                ELSE NVL(R.MEDIA_DESC, 0)
            END AS MEDIA_DESC_NUM,
            CASE
                WHEN T.SEQTIPOACRESCDESCTO = 2 THEN NVL(F.MAIOR_FISC, 0)
                ELSE NVL(R.MAIOR_DESC, 0)
            END AS MAIOR_DESC_NUM
        FROM CONSINCO.MFL_TIPOACRESCDESCTO T
        LEFT JOIN CTE_RESUMO_DF R
            ON R.SEQTIPOACRESCDESCTO = T.SEQTIPOACRESCDESCTO
        CROSS JOIN CTE_LOG_FISCAL_ITEM F
        WHERE NVL(T.INDTIPOACRESCDESCTO, 'D') = 'D'
    ),
    CTE_COM_TOTAL AS (
        SELECT /*+ MATERIALIZE */
            C.COD_TIPO,
            C.DESCRICAO_TIPO_DESCONTO,
            C.ORIGEM_DESCONTO,
            C.QTD_LOJAS,
            C.Q_LOJAS,
            C.QTD_CUPONS_VALIDOS,
            C.QTD_ITENS_COM_DESCONTO,
            C.VLR_DESC_NUM,
            C.MEDIA_DESC_NUM,
            C.MAIOR_DESC_NUM,
            ROUND(SUM(C.VLR_DESC_NUM) OVER (), 2) AS TOTAL_GERAL_DESC
        FROM CTE_CONSOLIDADO C
    )
    SELECT
        G.COD_TIPO,
        G.DESCRICAO_TIPO_DESCONTO,
        G.ORIGEM_DESCONTO,
        G.QTD_LOJAS,
        G.Q_LOJAS,
        G.QTD_CUPONS_VALIDOS,
        G.QTD_ITENS_COM_DESCONTO,
        'R$ ' || TO_CHAR(NVL(G.VLR_DESC_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS VLR_TOTAL_DESCONTO_RS,
        CASE
            WHEN NVL(G.TOTAL_GERAL_DESC, 0) > 0 THEN TO_CHAR(ROUND((NVL(G.VLR_DESC_NUM, 0) / G.TOTAL_GERAL_DESC) * 100, 2), 'FM999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') || ' %'
            ELSE '0,00 %'
        END AS PARTICIPACAO_NO_TOTAL,
        'R$ ' || TO_CHAR(NVL(G.MEDIA_DESC_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS TICKET_MEDIO_DESC_RS,
        'R$ ' || TO_CHAR(NVL(G.MAIOR_DESC_NUM, 0), 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS = '',.''') AS MAIOR_DESCONTO_RS
    FROM (
        SELECT
            1 AS ORDEM_BLOCO,
            T.COD_TIPO,
            T.DESCRICAO_TIPO_DESCONTO,
            T.ORIGEM_DESCONTO,
            T.QTD_LOJAS,
            T.Q_LOJAS,
            T.QTD_CUPONS_VALIDOS,
            T.QTD_ITENS_COM_DESCONTO,
            T.VLR_DESC_NUM,
            T.MEDIA_DESC_NUM,
            T.MAIOR_DESC_NUM,
            T.TOTAL_GERAL_DESC
        FROM CTE_COM_TOTAL T
        UNION ALL
        SELECT
            2 AS ORDEM_BLOCO,
            999 AS COD_TIPO,
            'TOTAL GERAL ->' AS DESCRICAO_TIPO_DESCONTO,
            'CONSOLIDADO' AS ORIGEM_DESCONTO,
            MAX(TL.QTD_LOJAS_GERAL) AS QTD_LOJAS,
            MAX(TL.Q_LOJAS_GERAL) AS Q_LOJAS,
            SUM(T.QTD_CUPONS_VALIDOS) AS QTD_CUPONS_VALIDOS,
            SUM(T.QTD_ITENS_COM_DESCONTO) AS QTD_ITENS_COM_DESCONTO,
            ROUND(SUM(T.VLR_DESC_NUM), 2) AS VLR_DESC_NUM,
            ROUND(AVG(NULLIF(T.MEDIA_DESC_NUM, 0)), 2) AS MEDIA_DESC_NUM,
            ROUND(MAX(T.MAIOR_DESC_NUM), 2) AS MAIOR_DESC_NUM,
            MAX(T.TOTAL_GERAL_DESC) AS TOTAL_GERAL_DESC
        FROM CTE_COM_TOTAL T
        CROSS JOIN CTE_TODAS_LOJAS_ATIVAS TL
    ) G
    ORDER BY
        G.ORDEM_BLOCO ASC,
        G.VLR_DESC_NUM DESC,
        G.COD_TIPO ASC
)
